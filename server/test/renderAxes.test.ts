import { strictEqual } from 'node:assert/strict';
import { describe, it } from 'node:test';

import type { AxisFillAnswer } from '../src/artifacts/renderAxes.ts';
import { applyAxisAnswers } from '../src/artifacts/renderAxes.ts';
import type { AxisName } from '../src/artifacts/planAxes.ts';

const NL = '\n';

function ось(name: string, affected: string, what: string, outcome: string): string {
  return `| ${name} | ${affected} | ${what} | ${outcome} |`;
}

function риск(axis: string, what = 'что-то ломается', why = 'пока допустимо', revisit = 'первый инцидент'): string {
  return `| ${axis} | ${what} | ${why} | ${revisit} |`;
}

function план(
  rows: string[],
  opts: { risks?: string[]; noRisksProse?: boolean } = {},
): string {
  const risksBlock =
    opts.risks !== undefined
      ? ['', '| Ось | Риск словами | Почему принимаем | Когда вернуться |', '|---|---|---|---|', ...opts.risks]
      : opts.noRisksProse === true
        ? ['', 'Принятых рисков нет.']
        : [];
  return [
    '# План: тест',
    '',
    '## Последствия шагов',
    '',
    '| Ось | Затронута шагами | Что именно в шагах | Исход |',
    '|---|---|---|---|',
    ...rows,
    ...risksBlock,
    '',
    '## Необратимые шаги',
    '',
    '- н/п',
    '',
  ].join(NL);
}

function answer(
  axis: AxisName,
  affectedText: string,
  what: string,
  outcome: string,
  risk?: { what: string; why: string; revisit: string },
): AxisFillAnswer {
  return risk === undefined ? { axis, affectedText, what, outcome } : { axis, affectedText, what, outcome, risk };
}

const ПОЛНЫЕ_ОСИ = [
  ось('Безопасность', 'нет', 'шаг 1', 'н/п — не затронута'),
  ось('Ресурсы и скорость', 'нет', 'шаг 1', 'н/п — не затронута'),
  ось('Отказы зависимостей', 'нет', 'шаг 1', 'н/п — не затронута'),
  ось('Настройки', 'нет', 'шаг 1', 'н/п — не затронута'),
  ось('Совместимость и данные', 'нет', 'шаг 1', 'н/п — не затронута'),
  ось('Наблюдаемость', '‹да/нет›', 'шаг 1', '‹исход›'),
];

describe('applyAxisAnswers: пустой ввод не трогает текст', () => {
  it('answers пуст — текст возвращается как есть', () => {
    const text = план(ПОЛНЫЕ_ОСИ);
    strictEqual(applyAxisAnswers(text, []), text);
  });

  it('секции «Последствия шагов» нет вовсе — текст без изменений', () => {
    const text = ['# План: тест', '', '## Необратимые шаги', '', '- н/п', ''].join(NL);
    const out = applyAxisAnswers(text, [answer('Безопасность', 'да', 'шаг 1', 'claim-1')]);
    strictEqual(out, text);
  });
});

describe('applyAxisAnswers: замена существующей строки', () => {
  it('заменяет ровно строку неотвеченной оси, остальные пять — байт-в-байт как были', () => {
    const before = план(ПОЛНЫЕ_ОСИ);
    const out = applyAxisAnswers(before, [
      answer('Наблюдаемость', 'да', 'шаг 1 пишет метрику', 'инвариант «время ответа не растёт»'),
    ]);
    const beforeLines = before.split(NL);
    const outLines = out.split(NL);
    // Все строки, кроме заменённой, идентичны исходным байт-в-байт.
    for (let i = 0; i < beforeLines.length; i++) {
      if (beforeLines[i] === ПОЛНЫЕ_ОСИ[5]) continue; // единственная строка, которой ждём замену
      strictEqual(outLines[i], beforeLines[i], `строка ${i} изменилась без запроса: ${beforeLines[i]}`);
    }
    ok(out.includes('| Наблюдаемость | да | шаг 1 пишет метрику | инвариант «время ответа не растёт» |'));
    ok(!out.includes('‹да/нет›'));
  });
});

describe('applyAxisAnswers: вставка отсутствующей строки', () => {
  it('ось отсутствует в таблице целиком — строка дописывается в конец таблицы осей', () => {
    const rows = ПОЛНЫЕ_ОСИ.slice(0, 5); // без «Наблюдаемость»
    const before = план(rows);
    const out = applyAxisAnswers(before, [answer('Наблюдаемость', 'да', 'шаг 2', 'claim-2')]);
    ok(out.includes('| Наблюдаемость | да | шаг 2 | claim-2 |'));
    // Пять исходных строк не пострадали.
    for (const row of rows) ok(out.includes(row), row);
  });

  it('несколько отсутствующих осей вставляются в каноническом порядке AXES', () => {
    const rows = [
      ось('Безопасность', 'нет', 'шаг 1', 'н/п — не затронута'),
      ось('Отказы зависимостей', 'нет', 'шаг 1', 'н/п — не затронута'),
    ];
    const before = план(rows);
    // Отвечаем в ПЕРЕВЁРНУТОМ порядке — вставка должна восстановить канонический.
    const out = applyAxisAnswers(before, [
      answer('Наблюдаемость', 'да', 'шаг 2', 'claim-2'),
      answer('Ресурсы и скорость', 'нет', 'шаг 1', 'н/п — не затронута'),
      answer('Настройки', 'нет', 'шаг 1', 'н/п — не затронута'),
      answer('Совместимость и данные', 'нет', 'шаг 1', 'н/п — не затронута'),
    ]);
    const idx = (needle: string): number => out.split(NL).findIndex((l) => l.includes(needle));
    ok(idx('Ресурсы и скорость') < idx('Настройки'));
    ok(idx('Настройки') < idx('Совместимость и данные'));
    ok(idx('Совместимость и данные') < idx('Наблюдаемость'));
  });
});

describe('applyAxisAnswers: таблица осей без КАНОНИЧЕСКИХ строк вообще (regression, живой замер axisfill-gptossrf-1, 2026-09-09)', () => {
  // Модель перепутала таблицу осей со списком пунктов задачи — строки «claim-1»…«claim-N»
  // вместо названий осей канона. Ни одна каноническая ось не находится В ТАБЛИЦЕ ОСЕЙ, зато
  // таблица ПРИНЯТЫХ РИСКОВ (своя, отдельная) уже содержит все 6 канонических имён (тоже
  // ошибка модели — риск заведён на каждую ось без разбора). До исправления сканирование не
  // останавливалось на второй шапке «Ось …» и находило «совпадения» уже в таблице рисков,
  // переписывая её строки поверх настоящим содержимым таблицы осей — «Последствия шагов»
  // оставались незаполненными, а топ-ап отчитывался успехом.
  const ЗАПУТАННЫЙ_ПЛАН = план(
    [
      ось('claim-1', 'да', 'шаг 1 меняет цену', ''),
      ось('claim-2', 'да', 'шаг 2 добавляет тест', ''),
    ],
    { risks: ['Безопасность', 'Ресурсы и скорость', 'Отказы зависимостей', 'Настройки', 'Совместимость и данные', 'Наблюдаемость'].map((a) => риск(a, 'да', 'ошибочно заведено моделью', 'claim-1')) },
  );

  it('ответы уходят в ТАБЛИЦУ ОСЕЙ (после существующих claim-строк), а не в таблицу рисков', () => {
    const out = applyAxisAnswers(ЗАПУТАННЫЙ_ПЛАН, [
      answer('Безопасность', 'нет', 'н/п', 'н/п — не затронута'),
      answer('Ресурсы и скорость', 'нет', 'н/п', 'н/п — не затронута'),
    ]);
    ok(out.includes('| Безопасность | нет | н/п | н/п — не затронута |'), out);
    ok(out.includes('| Ресурсы и скорость | нет | н/п | н/п — не затронута |'), out);
    // claim-строки таблицы осей остаются на месте, ответы вставлены ПОСЛЕ них.
    ok(out.includes(ось('claim-1', 'да', 'шаг 1 меняет цену', '')), out);
    const idxClaim2 = out.split(NL).findIndex((l) => l.startsWith('| claim-2'));
    const idxBezop = out.split(NL).findIndex((l) => l.startsWith('| Безопасность |'));
    ok(idxClaim2 !== -1 && idxBezop !== -1 && idxBezop > idxClaim2, 'новая строка оси идёт после claim-строк');
  });

  it('строки чужой таблицы рисков (ошибочно заведённые моделью) НЕ переписываются топ-апом', () => {
    const out = applyAxisAnswers(ЗАПУТАННЫЙ_ПЛАН, [
      answer('Безопасность', 'нет', 'н/п', 'н/п — не затронута'),
    ]);
    // Строка риска «Безопасность», ошибочно заведённая моделью, остаётся как была — топ-ап
    // не подчищает чужие ошибки, он только дополняет молчание (см. докстринг planAxisFill.ts).
    ok(out.includes(риск('Безопасность', 'да', 'ошибочно заведено моделью', 'claim-1')), out);
  });

  it('если ответ САМ несёт риск для оси, отсутствующей в таблице рисков — риск дописывается, не путается со старыми строками', () => {
    const план2 = план(
      [ось('claim-1', 'да', 'шаг 1', '')],
      { risks: [риск('Безопасность', 'да', 'ошибочно заведено моделью', 'claim-1')] },
    );
    const out = applyAxisAnswers(план2, [
      answer('Наблюдаемость', 'да', 'шаг 1 пишет метрику', 'риск', {
        what: 'алерт может не сработать',
        why: 'мониторинг чинится следующим витком',
        revisit: 'после первого прод-инцидента',
      }),
    ]);
    ok(out.includes('| Наблюдаемость | да | шаг 1 пишет метрику | риск |'));
    ok(
      out.includes(
        '| Наблюдаемость | алерт может не сработать | мониторинг чинится следующим витком | после первого прод-инцидента |',
      ),
      out,
    );
    ok(out.includes(риск('Безопасность', 'да', 'ошибочно заведено моделью', 'claim-1')), 'чужая строка риска цела');
  });
});

describe('applyAxisAnswers: таблица принятых рисков', () => {
  it('заменяет ровно строку риска нужной оси — «что»/«почему»/«когда» не путаются местами', () => {
    const before = план(ПОЛНЫЕ_ОСИ, { risks: [риск('Наблюдаемость', 'старый текст риска', 'старая причина', 'старый срок')] });
    const out = applyAxisAnswers(before, [
      answer('Наблюдаемость', 'да', 'шаг 1', 'риск', {
        what: 'алерт может не сработать',
        why: 'мониторинг чинится следующим витком',
        revisit: 'после первого прод-инцидента',
      }),
    ]);
    ok(
      out.includes(
        '| Наблюдаемость | алерт может не сработать | мониторинг чинится следующим витком | после первого прод-инцидента |',
      ),
      out,
    );
    ok(!out.includes('старый текст риска'));
  });

  it('строка риска для оси отсутствует, таблица рисков уже есть — дописывается в конец таблицы', () => {
    const before = план(ПОЛНЫЕ_ОСИ, { risks: [риск('Безопасность')] });
    const out = applyAxisAnswers(before, [
      answer('Наблюдаемость', 'да', 'шаг 1', 'риск', { what: 'w', why: 'y', revisit: 'r' }),
    ]);
    ok(out.includes(риск('Безопасность')), 'исходная строка риска цела');
    ok(out.includes('| Наблюдаемость | w | y | r |'));
  });

  it('таблицы рисков нет, есть строка-проза «принятых рисков нет» — строится таблица на её месте', () => {
    const before = план(ПОЛНЫЕ_ОСИ, { noRisksProse: true });
    const out = applyAxisAnswers(before, [
      answer('Наблюдаемость', 'да', 'шаг 1', 'риск', { what: 'w', why: 'y', revisit: 'r' }),
    ]);
    ok(!out.includes('Принятых рисков нет'));
    ok(out.includes('| Ось | Риск словами | Почему принимаем | Когда вернуться |'));
    ok(out.includes('| Наблюдаемость | w | y | r |'));
  });

  it('таблицы рисков нет и прозы про них тоже нет — таблица дописывается в конец секции', () => {
    const before = план(ПОЛНЫЕ_ОСИ);
    const out = applyAxisAnswers(before, [
      answer('Наблюдаемость', 'да', 'шаг 1', 'риск', { what: 'w', why: 'y', revisit: 'r' }),
    ]);
    ok(out.includes('| Ось | Риск словами | Почему принимаем | Когда вернуться |'));
    ok(out.includes('| Наблюдаемость | w | y | r |'));
    // Секция «Необратимые шаги» после нас — не задета.
    ok(out.includes('## Необратимые шаги'));
  });

  it('regression: таблица рисков уже есть (шапка+разделитель), но БЕЗ строк данных — вставка не ломает markdown (шапка/данные/разделитель по порядку)', () => {
    const before = план(ПОЛНЫЕ_ОСИ, { risks: [] });
    const out = applyAxisAnswers(before, [
      answer('Наблюдаемость', 'да', 'шаг 1', 'риск', { what: 'w', why: 'y', revisit: 'r' }),
    ]);
    const lines = out.split(NL);
    const headerIdx = lines.findIndex((l) => l === '| Ось | Риск словами | Почему принимаем | Когда вернуться |');
    ok(headerIdx !== -1, out);
    strictEqual(lines[headerIdx + 1], '|---|---|---|---|');
    strictEqual(lines[headerIdx + 2], '| Наблюдаемость | w | y | r |');
  });
});

describe('applyAxisAnswers: таблица осей БЕЗ шапки (regression, planAxes.ts поддерживает потерянную шапку)', () => {
  // Виток из терминала (без раннера) может потерять шапку «Ось | Затронута шагами | …» —
  // `planAxes.ts`'s `kindOfTable` это учитывает эвристикой «вторая ячейка похожа на
  // да/нет». `applyAxisAnswers` обязана согласованно её же применять, иначе первая
  // РЕАЛЬНАЯ шапка «Ось …» в файле (шапка таблицы РИСКОВ) принимается за шапку осей.
  const БЕЗГОЛОВЫЙ_ПЛАН = [
    '# План: тест',
    '',
    '## Последствия шагов',
    '',
    ось('Безопасность', 'нет', 'шаг 1', 'н/п — не затронута'),
    ось('Ресурсы и скорость', 'нет', 'шаг 1', 'н/п — не затронута'),
    '',
    '| Ось | Риск словами | Почему принимаем | Когда вернуться |',
    '|---|---|---|---|',
    риск('Безопасность', 'да', 'уже принят', 'claim-1'),
    '',
    '## Необратимые шаги',
    '',
    '- н/п',
    '',
  ].join(NL);

  it('недостающая ось вставляется В ТАБЛИЦУ ОСЕЙ (после существующих безголовых строк), не путается со строками риска', () => {
    const out = applyAxisAnswers(БЕЗГОЛОВЫЙ_ПЛАН, [
      answer('Отказы зависимостей', 'нет', 'н/п', 'н/п — не затронута'),
    ]);
    ok(out.includes(ось('Отказы зависимостей', 'нет', 'н/п', 'н/п — не затронута')), out);
    const lines = out.split(NL);
    const idxRes = lines.findIndex((l) => l.startsWith('| Ресурсы и скорость'));
    const idxDep = lines.findIndex((l) => l.startsWith('| Отказы зависимостей'));
    const idxRiskHeader = lines.findIndex((l) => l === '| Ось | Риск словами | Почему принимаем | Когда вернуться |');
    ok(idxRes !== -1 && idxDep !== -1 && idxRiskHeader !== -1, out);
    ok(idxDep > idxRes && idxDep < idxRiskHeader, 'новая строка оси — между существующими строками осей и таблицей рисков');
  });

  it('таблица рисков (безголовой таблицы осей) не дублируется и не портится', () => {
    const out = applyAxisAnswers(БЕЗГОЛОВЫЙ_ПЛАН, [
      answer('Отказы зависимостей', 'нет', 'н/п', 'н/п — не затронута'),
    ]);
    const occurrences = out.split('Риск словами').length - 1;
    strictEqual(occurrences, 1, out);
    ok(out.includes(риск('Безопасность', 'да', 'уже принят', 'claim-1')), 'исходная строка риска цела');
  });
});

function ok(cond: boolean, msg?: string): void {
  if (!cond) throw new Error(msg ?? 'assertion failed');
}
