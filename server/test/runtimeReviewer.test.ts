/**
 * Ревью, запущенное рантаймом (этап 6).
 *
 * Методология требует независимого рецензента, но до сих пор его вызов держался на том,
 * что модель этапа догадается позвать `Task`. На дешёвой полке это ровно тот шаг, который
 * не случается: замеры дали залипание анти-цикла на `Task` ×3, уход хода в оболочку и
 * нехватку ходов до вызова (`docs/model-runs.md`). Раз гейты прогоняет рантайм, ревью —
 * той же природы: шаг этапа, а не поручение.
 */

import { ok } from 'node:assert/strict';
import { describe, it } from 'node:test';

import { reviewerBlock } from '../src/run/Run.ts';

describe('блок отчёта рецензента во входе этапа 6', () => {
  it('несёт текст рецензента дословно', () => {
    const block = reviewerBlock('Расхождение: claim-2 не подтверждён — тест проверяет не ту границу.');
    ok(block.includes('claim-2 не подтверждён'));
  });

  it('прямо запрещает повторный вызов субагента', () => {
    // Иначе дешёвая модель тратит ходы на ревью, которое уже состоялось, — а анти-цикл
    // на `Task` ×3 её же и обрывает, уже ПОСЛЕ прогона гейтов.
    const block = reviewerBlock('находок нет');
    ok(/Повторно звать субагента `Task` не надо/.test(block), block);
  });

  it('подаёт находки как факт прогона, а не как мнение', () => {
    const block = reviewerBlock('находок нет');
    ok(block.includes('прогон рантайма'));
    ok(/роняет вердикт/.test(block), block);
  });
});
