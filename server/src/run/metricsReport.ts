/**
 * Персистентный отчёт метрик витка (`metrics.md`) — человекочитаемый рендер того же
 * снапшота, что уходит в `metrics.json`.
 *
 * Собирается кодом из уже посчитанного: второго источника чисел нет и модель их не
 * сочиняет. Строго наблюдаемое: счётчики прогонов, время ожидания человека, незакрытые
 * плейсхолдеры. «Почему гейт падал» рантайм не знает, и такой строки здесь нет.
 */

import type { RunMetrics } from '@sdlc-runner/shared';
import { formatDuration } from '@sdlc-runner/shared';

/**
 * `null` — витку нечего рассказать ни в одной из секций: ни одного прогона гейтов, ни
 * одного ожидания человека, ни одного незакрытого плейсхолдера. Пустая секция хуже
 * отсутствующей: она читается как «проблем не было», а не «смотреть было нечего».
 */
export function metricsBlock(m: RunMetrics): string | null {
  if (m.gates.length === 0 && m.human.length === 0 && m.artifactGaps.length === 0) {
    return null;
  }

  const lines = [
    '## Метрики витка (посчитано рантаймом)',
    '',
    'Числа ниже — наблюдения рантайма, а не оценка. Машиночитаемый снапшот тех же чисел —',
    'в `metrics.json` рядом; расхождение этого файла с ним исключено: рендерится он из него.',
  ];

  if (m.gates.length > 0) {
    lines.push(
      '',
      '| Гейт | Прогонов | ❌ | ⏭ у включённого | Время |',
      '|---|---|---|---|---|',
      ...m.gates.map(
        (g) =>
          `| ${g.gate} | ${g.runs} | ${g.red} | ${g.skippedWhileEnabled} | ` +
          `${formatDuration(g.durationMs)} |`,
      ),
      '',
      '⏭ у включённого — прогон, где гейт был в наборе и включён, но проверка не состоялась ' +
        '(нет инструмента, отказ среды, таймаут). Выключенный гейт сюда не попадает: его ' +
        'состояние — предмет таблицы «Долг» набора проекта.',
    );
  }

  if (m.human.length > 0) {
    lines.push(
      '',
      '| Этап | Вопросов | Одобрений | Ждал человека |',
      '|---|---|---|---|',
      ...m.human.map(
        (h) => `| ${h.stage} | ${h.questions} | ${h.approvals} | ${formatDuration(h.waitMs)} |`,
      ),
      '',
      '«Ждал человека» — суммарное время от постановки запроса в очередь до решения ' +
        'оператора. Автоодобрения по правилам и отказы политики сюда не входят: они человека ' +
        'не ждали.',
    );
  }

  if (m.artifactGaps.length > 0) {
    lines.push(
      '',
      '| Артефакт | Незаполненных мест ‹…› |',
      '|---|---|',
      ...m.artifactGaps.map((g) => `| ${g.artifact} | ${g.placeholders} |`),
      '',
      'Счётчик — последний на момент записи метрик: артефакт, дозаполненный позже, из таблицы ' +
        'исчезает.',
    );
  }

  return lines.join('\n');
}
