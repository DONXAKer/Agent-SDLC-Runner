import { basename } from 'node:path';
import { readArtifact, writeArtifact } from '../artifacts/artifact.ts';
import { isPreparationV2, requireStructuredPreparationTables } from '../artifacts/preparation.ts';
import type { WitokPaths } from '../artifacts/paths.ts';
import type { SeededArtifact } from './seed.ts';

/** Меняем только только что созданные формы; существующие документы не переписываем. */
export function seedPreparationForms(paths: WitokPaths, seeded: SeededArtifact[]): void {
  if (!isPreparationV2(paths)) return;
  for (const item of seeded) {
    const old = readArtifact(item.path).text;
    const marker = /^<!-- sdlc-template: .* -->/mu.exec(old)?.[0] ?? '';
    let text = old;
    if (basename(item.path) === 'intent.md') text = `${marker}
# Задача: ‹название›

> Проработка v3. ИИ готовит структурированный черновик; человек подтверждает требования вместе с планом.
- **Контур:** полный
- **Ветка витка:** ‹ветка›

## Коротко
‹аудитория и ожидаемый результат›

## Зачем
‹какую проблему решаем›

## Что делаем
‹наблюдаемое изменение поведения›

## Чего не делаем
‹явно заданные границы; неизвестное помечай предположением›

## Приёмочный лист
Предварительный список; уточняется после исследования, до реализации.
| id | Пункт | Как проверить (процедура + критерий) |
|----|-------|--------------------------------------|

## Основания и сценарии
| Основание | Сценарий | Контрпример | ID |
|-----------|----------|------------|----|

## Инварианты
н/п — проектных инвариантов пока не выявлено; проверить при исследовании

## Когда остановиться и спросить
Новый существенный контракт, изменение поведения или противоречие исходному запросу.

## Что придётся тронуть
Будет уточнено исследованием.

## Открытые вопросы
Нет зафиксированных вопросов; выявить существенные неизвестные при исследовании.
`;
    if (basename(item.path) === 'intent.md') {
      requireStructuredPreparationTables(paths);
      const tables = [...text.matchAll(/^\|[^\n]+\|\r?\n\|[-| :]+\|$/gmu)];
      const blocks = [
        '<!-- sdlc-json:acceptance:start -->\n‹acceptance_json›\n<!-- sdlc-json:acceptance:end -->',
        '<!-- sdlc-json:basis:start -->\n‹basis_json›\n<!-- sdlc-json:basis:end -->',
      ];
      for (let i = Math.min(tables.length, blocks.length) - 1; i >= 0; i--) {
        const match = tables[i]!;
        text = text.slice(0, match.index) + blocks[i] + text.slice(match.index + match[0].length);
      }
    }
    if (basename(item.path) === 'readiness.md') text = `${marker}
# Готовность задачи: ‹название витка›

## Прогон 1 — перед разведкой
- **Дата:** ‹дата›
- **Проверки:** ‹проверки прогона 1›
- **Вердикт прогона 1:** ‹готова / не готова›

## Прогон 2 — перед реализацией
- **Дата:** ‹дата›
- **Проверки:** ‹проверки прогона 2›
- **Вердикт прогона 2:** ‹готова / не готова›

Готовность к исследованию требует цели и границ. Готовность к реализации требует согласованных требований, сценариев, проверок и контрпримеров, закрытых существенных вопросов и независимой проверки плана. Число строк не является критерием полноты.
`;
    if (basename(item.path) === 'plan.md') text += '\n## Изменения требований\n‹различия с предыдущей редакцией, причины добавления или удаления claims; для первой редакции — уточнения исходного запроса›\n';
    if (basename(item.path) === 'exploration-report.md') text = text.replace(/^.*\*\*Решение человека о полноте[^\n]*$/gmu, '> Полнота требований подтверждается вместе с планом после независимой проверки.');
    if (basename(item.path) === 'exploration-report.md') text = `${marker}
# Отчёт разведки: ‹название витка›

## Краткий вывод
‹что в коде определяет решение и проверку›

## Карта кодовой базы
Указывай только прочитанные файлы и факты, влияющие на задачу. Если файл надо создать, пометь путь словом «новый».

| Файл / путь | Символ или тест | Что подтверждено источником | Значение для задачи |
|---|---|---|---|
| ‹путь› | ‹символ или тест› | ‹факт из прочитанного кода› | ‹влияние на решение или проверку› |

## Переиспользование
‹существующий механизм и как задача должна его использовать; либо «подходящего механизма не найдено»›

## Файлы для изменения
| Файл / путь | Изменение |
|---|---|
| ‹путь› | ‹что изменится; новый файл пометь словом «новый»› |

## Проверки
- ‹сценарий или инвариант› — ‹как проверить и ожидаемый результат›

## Риски и границы
‹только подтверждённые риски и явно заданные ограничения; если дополнительных рисков не найдено, так и напиши›

## Вопросы человеку
‹нерешённый выбор, меняющий наблюдаемое поведение; либо «нет»›

> Требования проверяются вместе с планом после независимой проверки.
`;
    if (basename(item.path) === 'plan.md') text = `${marker}
# План: ‹название витка›
- **Задача:** intent.md
- **Одобрение:** ‹имя и дата› / не одобрен — реализация не начинается

## Подход
Выбери один вариант до кода. Сверь контракт и тесты из разведки; объясни, почему выбранный способ сохраняет требуемое поведение.

‹Выбранный подход по исходному запросу и прочитанным контрактам; ссылки на реальные исходники и тесты, контрпример для отвергнутой альтернативы, если она есть.›

## Шаги
### Шаг 1 — Изменить требуемое поведение
- файл: ‹существующий путь› (существующий)
- символ: ‹реальный символ из исследования; для добавляемого символа укажи «новый: имя»›
- действие: ‹одно проверяемое изменение›
- закрывает: ‹все подходящие claim-N; перечисли несколько, если шаг покрывает несколько›
- проверка: ‹что подтвердит результат› · ожидаемо: ‹результат›
- контракт: ‹до → после; потребители›
- зависит от: нет
- факты человека: н/п

### Шаг 2 — Проверить требуемое поведение
- файл: ‹новый путь теста› (новый)
- символ: ‹имя нового теста›
- действие: добавить тесты для каждого требования, которое можно проверить поведением, включая запреты и регрессионные границы
- закрывает: ‹все подходящие claim-N про поведение, новые тесты и неизменность существующих тестов›
- проверка: ‹команда тестов проекта› · ожидаемо: все тесты зелёные
- контракт: н/п — тест
- зависит от: 1
- факты человека: н/п

## files_to_touch
| Путь | Что делаем |
|---|---|
| ‹путь из исследования› | ‹изменение по требованию› |
| ‹новый test-файл› | ‹новые тесты› |

## Из задачи исключено
‹пути или поведение, которое задача запрещает менять; либо «расхождений с задачей нет»›

## Проверки приёмки
| ID | Наблюдаемое поведение | Процедура | Ожидаемый результат |
|---|---|---|---|
| claim-1 | ‹поведение› | ‹проверка› | ‹результат› |
| claim-2 | ‹поведение› | ‹проверка› | ‹результат› |
| claim-3 | ‹поведение› | ‹проверка› | ‹результат› |

## Последствия шагов
| Ось | Затронута шагами | Что именно в шагах | Исход |
|---|---|---|---|
| Безопасность | ‹да/нет› | ‹шаг и путь:символ либо причина› | ‹claim-N / инвариант / гейт «имя» / риск / следующий виток: вопрос N / н/п — причина› |
| Ресурсы и скорость | ‹да/нет› | ‹шаг и путь:символ либо причина› | ‹допустимый исход› |
| Отказы зависимостей | ‹да/нет› | ‹шаг и путь:символ либо причина› | ‹допустимый исход› |
| Настройки | ‹да/нет› | ‹шаг и путь:символ либо причина› | ‹допустимый исход› |
| Совместимость и данные | ‹да/нет› | ‹шаг и путь:символ либо причина› | ‹допустимый исход› |
| Наблюдаемость | ‹да/нет› | ‹шаг и путь:символ либо причина› | ‹допустимый исход› |

## Изменения требований
‹нет изменений; выбранный подход обоснован исходным запросом и кодом›
`;
    if (text !== old) { writeArtifact(item.path, text); item.snapshot = text; }
  }
}
