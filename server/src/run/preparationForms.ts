import { basename } from 'node:path';
import { readArtifact, writeArtifact } from '../artifacts/artifact.ts';
import { isPreparationV2 } from '../artifacts/preparation.ts';
import type { WitokPaths } from '../artifacts/paths.ts';
import type { SeededArtifact } from './seed.ts';

/** Меняем только только что созданные формы; существующие документы не переписываем. */
export function seedPreparationForms(paths: WitokPaths, seeded: SeededArtifact[]): void {
  if (!isPreparationV2(paths)) return;
  for (const item of seeded) {
    const old = readArtifact(item.path).text;
    const marker = /^<!-- sdlc-template: .* -->/mu.exec(old)?.[0] ?? '';
    let text = old;
    if (basename(item.path) === 'intent.md') text = `${marker}
# Задача: ‹название›

> Проработка v2. ИИ готовит черновик; человек подтверждает требования вместе с планом.
- **Контур:** полный
- **Ветка витка:** ‹ветка›

## Коротко
‹аудитория и ожидаемый результат›

## Зачем
‹какую проблему решаем›

## Что делаем
‹наблюдаемое изменение поведения›

## Чего не делаем
‹явно заданные границы; неизвестное помечай предположением›

## Приёмочный лист
Предварительный список; уточняется после исследования, до реализации.
| id | Пункт | Как проверить (процедура + критерий) |
|----|-------|--------------------------------------|

## Основания и сценарии
| Основание | Сценарий | Контрпример | ID |
|-----------|----------|------------|----|

## Инварианты
н/п — проектных инвариантов пока не выявлено; проверить при исследовании

## Когда остановиться и спросить
Новый существенный контракт, изменение поведения или противоречие исходному запросу.

## Что придётся тронуть
Будет уточнено исследованием.

## Открытые вопросы
Нет зафиксированных вопросов; выявить существенные неизвестные при исследовании.
`;
    if (basename(item.path) === 'readiness.md') text = `${marker}
# Готовность задачи: ‹название витка›

## Прогон 1 — перед разведкой
- **Дата:** ‹дата›
- **Проверки:** ‹проверки прогона 1›
- **Вердикт прогона 1:** ‹готова / не готова›

## Прогон 2 — перед реализацией
- **Дата:** ‹дата›
- **Проверки:** ‹проверки прогона 2›
- **Вердикт прогона 2:** ‹готова / не готова›

Готовность к исследованию требует цели и границ. Готовность к реализации требует согласованных требований, сценариев, проверок и контрпримеров, закрытых существенных вопросов и независимой проверки плана. Число строк не является критерием полноты.
`;
    if (basename(item.path) === 'plan.md') text += '\n## Изменения требований\n‹различия с предыдущей редакцией, причины добавления или удаления claims; для первой редакции — уточнения исходного запроса›\n';
    if (basename(item.path) === 'exploration-report.md') text = text.replace(/^.*\*\*Решение человека о полноте[^\n]*$/gmu, '> Полнота требований подтверждается вместе с планом после независимой проверки.');
    if (text !== old) { writeArtifact(item.path, text); item.snapshot = text; }
  }
}
