/**
 * Содержимое артефакта, напечатанное в ответ вместо вызова инструмента.
 *
 * Наблюдение, повторившееся на всех замеренных локальных моделях (`docs/model-runs.md`):
 * модель СОСТАВЛЯЕТ артефакт правильно и печатает его текстом —
 *
 *     ### Файл `chunk-1-journal.md`
 *     ```
 *     # Журнал chunk'а 1: …
 *     ```
 *
 * — но `Write`/`Edit` не зовёт ни разу. Этап при этом честно красный: на диске бланк.
 * Порог здесь не в понимании задачи и не в окне контекста, а в переходе «сказать» → «сделать».
 *
 * Разбор ниже этот переход достраивает: найденный блок превращается в обычную запись,
 * которая идёт тем же путём, что и любая другая, — через политику и гейт одобрения. Это
 * важнее самой возможности: рантайм не «доверяет тексту», он предлагает вызов, который
 * оператор видит и может отклонить.
 *
 * Чего здесь НЕТ намеренно: угадывания пути. Блок принимается, только если рядом названо
 * имя файла, который этап и так обязан произвести. Иначе разбор начал бы писать файлы по
 * случайным упоминаниям в рассуждениях модели.
 */

/** Сколько строк между упоминанием имени и началом блока ещё считается «рядом». */
const NEAR_LINES = 4;

export interface SalvagedBlock {
  /** Путь, как он объявлен этапом в `produces` — не тот, что назвала модель. */
  path: string;
  content: string;
}

/** Имя файла без каталогов — то, чем модель называет артефакт в тексте. */
function basename(p: string): string {
  const parts = p.split(/[\\/]/);
  return parts[parts.length - 1] ?? p;
}

/**
 * Блоки, которые модель напечатала вместо записи.
 *
 * `produces` — абсолютные пути артефактов этапа; сопоставление идёт по имени файла, потому
 * что именно им модель и оперирует в тексте.
 */
export function salvageBlocks(text: string, produces: readonly string[]): SalvagedBlock[] {
  if (text.trim() === '') return [];

  const lines = text.split('\n');
  const found = new Map<string, string>();

  // Индексы открывающих ограждений: тройная кавычка в начале строки, возможно с языком.
  for (let i = 0; i < lines.length; i++) {
    const open = /^\s*```/.exec(lines[i] ?? '');
    if (open === null) continue;

    // Закрывающее ограждение — первая следующая строка из одних кавычек.
    let end = -1;
    for (let j = i + 1; j < lines.length; j++) {
      if (/^\s*```\s*$/.test(lines[j] ?? '')) {
        end = j;
        break;
      }
    }
    if (end < 0) break; // блок не закрыт — содержимое неполно, писать его нельзя

    // Кому принадлежит блок: ищем имя артефакта в нескольких строках НАД ним.
    const from = Math.max(0, i - NEAR_LINES);
    const head = lines.slice(from, i).join('\n');
    const owner = produces.find((p) => head.includes(basename(p)));

    if (owner !== undefined && !found.has(owner)) {
      const body = lines.slice(i + 1, end).join('\n');
      // Пустой блок — не содержимое, а разметка вокруг ничего.
      if (body.trim() !== '') found.set(owner, body.endsWith('\n') ? body : `${body}\n`);
    }

    i = end; // вложенных блоков не бывает: следующий поиск идёт после закрывающего
  }

  return [...found.entries()].map(([path, content]) => ({ path, content }));
}
