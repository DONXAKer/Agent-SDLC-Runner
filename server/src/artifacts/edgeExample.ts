/**
 * Образец граничного пункта приёмки — из ПРИМЕРА методологии, читается в рантайме.
 *
 * Зачем. Замер 2026-09-04 (`qwen3-coder-30b-a3b`, три плеча по 5 прогонов, см.
 * `docs/model-runs.md`): модель пишет 6–33 пункта приёмки при норме 3 и НОЛЬ из них с
 * тегом `[edge]` — в четырёх прогонах базы из пяти. Барьер не в форме ответа (её сняла
 * отдельная починка того же дня), а в содержании: «граничный случай» просьбой не
 * порождается. Просьба при этом повторяется дважды — в карточке поля и в доборе, — и оба
 * раза называет только формат.
 *
 * В эталоне лежит `example/intent.md` с настоящими `[edge]`-пунктами. Копировать их в
 * репозиторий нельзя (правило: текстов методологии здесь нет, они читаются на месте) — и
 * не нужно: путь к эталону раннер и так знает.
 *
 * Нормы («не меньше двух») здесь не называются намеренно: число живёт в тексте этапа, и
 * второе место, называющее его, разошлось бы с первым (то же правило, что в
 * `FormFillExecutor.askClaimsTopUp`).
 */

import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

/** Длиннее этого строку не берём: карточка поля не должна распухнуть от одного образца. */
const MAX_ROW_BYTES = 400;

/**
 * Первая строка таблицы приёмочного листа с тегом `[edge]` из `example/intent.md` эталона.
 *
 * `null` — эталона нет, примера в нём нет или он не годится в образец. Тогда всё
 * работает как раньше: отсутствие примера не повод не спрашивать поле.
 */
export function edgeExampleRow(methodologyDir: string): string | null {
  const path = join(methodologyDir, 'example', 'intent.md');
  if (!existsSync(path)) return null;

  let text: string;
  try {
    text = readFileSync(path, 'utf8');
  } catch {
    return null;
  }

  // Ищем в секции приёмочного листа, а не по всему файлу: `[edge]` встречается и в
  // легенде, и в чек-листе готовности, и строкой оттуда образец быть не может.
  const section = text.split(/^##\s+Приёмочный лист/m)[1]?.split(/^##\s/m)[0];
  if (section === undefined) return null;

  for (const line of section.split('\n')) {
    const row = line.trim();
    if (!/^\|\s*claim-\d+\s*\|/.test(row)) continue;
    if (!row.includes('[edge]')) continue;
    // Незаполненный образец шаблона граничным пунктом не является.
    if (row.includes('‹')) continue;
    if (Buffer.byteLength(row, 'utf8') > MAX_ROW_BYTES) continue;
    return row;
  }
  return null;
}

/**
 * Блок для промпта: образец плюс одна строка о том, что это образец, а не содержание.
 *
 * Пустой массив, когда примера нет — вызывающий подставляет его в список строк без
 * условий на своей стороне.
 */
export function edgeExampleLines(methodologyDir: string): string[] {
  const row = edgeExampleRow(methodologyDir);
  if (row === null) return [];
  return [
    '',
    'Так граничный пункт выглядит в примере методологии — это образец МЫСЛИ, а не ' +
      'содержания: твои граничные пункты про пороги твоей задачи, а не про этот чужой пример.',
    '',
    '```',
    row,
    '```',
  ];
}
