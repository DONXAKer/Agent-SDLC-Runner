/**
 * Пример «мысль → вызов инструмента» для слабой модели — из РЕАЛЬНОГО бланка этапа.
 *
 * Пример не зашивается текстом: копия строки методологии в коде разошлась бы с шаблоном
 * при первой его правке (первая версия и разошлась — учила `- **Зачем:** ‹…›`, которого
 * в шаблоне интента нет). Берётся первый настоящий плейсхолдер первого разложенного
 * артефакта ЭТОГО этапа: такой `old_string` гарантированно найдётся, а путь гарантированно
 * разрешён к записи. Бланков с плейсхолдерами нет — примера нет, блок молчит.
 */
/**
 * Пример «мысль → FillField» для режима `compactForms ∈ {fill, all}` — тем же приёмом,
 * что обычный few-shot: берётся РЕАЛЬНОЕ первое поле модели из уже разложенного бланка
 * этого этапа, а не переписанная копия шаблона (та однажды разошлась с формой при первой
 * же её правке). `null` — нечем показать: бланка нет, или у него нет ни одного поля модели.
 */
function fillFieldFewShot(i: BuildPromptInput, path: string, text: string): string[] | null {
  const key = ARTIFACT_KEYS.find(
    (k) => artifactPathOf(i.ctx.paths, k, i.ctx.chunk, i.ctx.attempt) === path,
  );
  if (key === undefined) return null;
  const schema = deriveSchema(text, templateNameFor(path));
  const field = modelFields(schema, i.stage.id)[0];
  if (field === undefined) return null;
  const callJson = JSON.stringify({
    tool: 'FillField',
    arguments: { artifact: key, field: field.id, value: '(твоё содержимое по факту задачи)' },
  });
  return [
    '- Как выглядит сделанный шаг. Вот настоящее незаполненное поле твоего бланка — ' +
      'правильное действие это ОДИН вызов инструмента со значением поля, без разметки:',
    '  ```json',
    `  ${callJson}`,
    '  ```',
    '  Метку поля («- **Метка:** …») в значении повторять не надо — рантайм сам найдёт ' +
      'место и нарисует разметку. Когда в артефакте не осталось `‹…›` — вызови ' +
      '`FinalizeArtifact` с путём артефакта.',
    '- НЕПРАВИЛЬНО: печатать содержимое файла текстом в ответе, самому вписывать `|` или ' +
      '`**`, спрашивать человека о том, что видно из кода.',
  ];
}

function fewShotLines(i: BuildPromptInput): string[] {
  const useFillField = i.flow === 'loop' && (i.compactForms === 'fill' || i.compactForms === 'all');
  for (const path of i.stage.produces(i.ctx)) {
    const a = readArtifact(path);
    if (!a.exists) continue;

    if (useFillField) {
      const lines = fillFieldFewShot(i, path, a.text);
      if (lines !== null) return lines;
      continue;
    }

    const r = placeholderRanges(a.text)[0];
    if (r === undefined) continue;

    const lineStart = a.text.lastIndexOf('\n', r.start - 1) + 1;
    const lineEnd = a.text.indexOf('\n', r.start);
    const line = a.text.slice(lineStart, lineEnd < 0 ? a.text.length : lineEnd).trim();
    if (line === '' || line.length > 200) continue;

    const rel = toPosix(relative(i.ctx.paths.projectRoot, path));
    const filledLine = line.replace(r.text, '(твоё содержимое по факту задачи)');
    const callJson = JSON.stringify({
      tool: 'Edit',
      arguments: { file_path: rel, old_string: line, new_string: filledLine },
    });
    return [
      '- Как выглядит сделанный шаг. Вот настоящая незаполненная строка твоего бланка — ' +
        'правильное действие это ОДИН вызов инструмента с готовым содержимым:',
      '  ```json',
      `  ${callJson}`,
      '  ```',
      '  Когда в артефакте не осталось `‹…›` — вызови `FinalizeArtifact` с путём артефакта.',
      '- НЕПРАВИЛЬНО: печатать содержимое файла текстом в ответе (текст никуда не ' +
        'записывается), спрашивать человека о том, что видно из кода, продолжать читать ' +
        'файлы, когда контекста для правки уже достаточно.',
    ];
  }
  return [];
}

function fence(path: string, text: string, maxBytes: number, projected = false): string {
  const r = capBytes(text, maxBytes);
  const body = r.capped
    ? `${r.text}\n…[обрезано рантаймом: файл длиннее ${maxBytes} байт]`
    : r.text;
  const label = projected
    ? `<!-- ${path} · сжатая проекция: значения полей без легенд и разметки; полный текст — Read -->`
    : `<!-- ${path} -->`;
  return ['````markdown', label, body, '````'].join('\n');
}

/**
 * Карточка фактов от человека — блок промпта этапа 5. `null` — фактов нет.
 *
 * Экспортирована, потому что тот же блок нужен исполнителю по шагам (`StepExecutor`):
 * у него свой запрос на шаг, и собирать карточку второй раз своим кодом значило бы
 * завести два разных представления одних и тех же ответов человека.
 */
export function humanFactsBlock(clarificationReportPath: string): string | null {
  const clar = readArtifact(clarificationReportPath);
  const facts = clar.exists ? extractHumanFacts(clar.text) : [];
  if (facts.length === 0) return null;
  return [
    '## Факты от человека — обязаны попасть в код',
    '',
    'Это ответы человека из clarification-report.md, дословно. Каждое число и каждая ' +
      'цитата из ответа обязаны быть отражены в правке; потерянный ответ человека — ' +
      'прямой путь к красному вердикту этапа 6.',
    facts
      .map(
        (f) =>
          `- **${f.question}** → ${f.answer}` +
          (f.literals.length === 0
            ? ''
            : ` _(проверяемые литералы: ${f.literals.map((l) => l.shown).join(', ')})_`),
      )
      .join('\n'),
  ].join('\n\n');
}

/**
 * Запас под ответ модели при подрезке блока индекса под окно — фиксированное число, а не
 * `params.max_tokens`: этот параметр сюда не приходит (промпт собирается до выбора
 * провайдера), и заниженный запас безопаснее, чем отсутствие запаса вовсе.
 */
const EXPLORE_INDEX_RESPONSE_MARGIN_TOKENS = 4_096;

function userMessage(i: BuildPromptInput, systemBytes = 0): string {
  const parts: string[] = [];

  if (i.requirement !== undefined && i.requirement.trim() !== '') {
    parts.push('## Задача от человека', '', i.requirement.trim());
  }

  const inputs = stageInputs(i.stage.id, i.ctx);
  const present: string[] = [];
  const missing: string[] = [];

  const maxBytes =
    i.flow === 'loop' && LOOP_CAPPED_STAGES.has(i.stage.id)
      ? LOOP_MAX_ARTIFACT_BYTES
      : MAX_ARTIFACT_BYTES;
  // Компактная проекция: значения полей без легенд, цитат и разметки таблиц —
  // `artifacts/sheet.ts: renderSheet`. Только на loop-этапах-документах и на плане,
  // поданном во вход chunk'а: verify/handoff и патчи читает независимый рецензент, и
  // «лучше промпт не влез, чем вердикт по трети правки» здесь сильнее экономии контекста.
  // Проекция БЕЗ ПОТЕРЬ содержимого (не фильтрует по схеме) — режется тем же потолком,
  // что и полный текст, а не отдельным, более щедрым: цель этого режима — не тратить
  // выигранные байты обратно на больший лимит, а оставить с той же формой больше места
  // истории хода.
  const compact = i.compactForms === 'inputs' || i.compactForms === 'all';
  for (const input of inputs) {
    const a = readArtifact(input.path);
    const rel = toPosix(relative(i.ctx.paths.projectRoot, input.path));
    // Патч прошлой попытки на chunk флоу loop режется по локальному потолку, а не по
    // общему: план и журнал обязаны доехать целиком («лучше промпт не влез, чем вердикт
    // по трети правки» — это про этап 6), а прошлый патч — контекст, не предмет работы,
    // и на окне 16k он вытеснял план. Что именно чинить, приходит выжимкой ретрая.
    const cap =
      i.flow === 'loop' && i.stage.id === 'chunk' && rel.endsWith('.patch')
        ? LOOP_MAX_ARTIFACT_BYTES
        : maxBytes;
    if (!a.exists) {
      if (!input.optional) missing.push(rel);
      continue;
    }
    const useProjection =
      compact &&
      i.flow === 'loop' &&
      (LOOP_CAPPED_STAGES.has(i.stage.id) || (i.stage.id === 'chunk' && input.path === i.ctx.paths.plan));
    const text = useProjection ? renderSheet(a.text) : a.text;
    present.push(fence(rel, text, cap, useProjection));
  }

  if (present.length > 0) {
    parts.push('## Входные артефакты', '', present.join('\n\n'));
  }

  // Тело брифа этой попытки посчитано ЗДЕСЬ, а не на месте `push` ближе к концу функции
  // (было так раньше): бюджет блока «Индекс проекта» ниже считает остаток окна по
  // `parts`, собранным НА ЭТОТ МОМЕНТ, а бриф физически добавляется в `parts` намного
  // позже (после карточки человека — recency, см. комментарий там) — расчёт бюджета не
  // видел его тело вовсе. `extra` не привязан к конкретному этапу (общий HTTP-параметр
  // ручного повтора любого этапа), поэтому оценивается тут безусловно, не только для
  // `stage.id === 'chunk'` (code-review-all, 2026-09-14).
  const extraText = i.extra !== undefined && i.extra.trim() !== '' ? i.extra.trim() : null;
  const extraBrief = extraText === null || i.flow !== 'loop' ? null : capBytes(extraText, 2 * LOOP_MAX_ARTIFACT_BYTES);
  const extraBlockText =
    extraText === null
      ? null
      : extraBrief === null
        ? extraText
        : extraBrief.capped
          ? `${extraBrief.text}\n…[обрезано рантаймом: бриф длиннее потолка]`
          : extraBrief.text;

  // Индекс проекта — только этап 2 и только под ручкой (`BuildPromptInput.exploreIndex`).
  // Три правила рядом с данными, а не в adapter-блоке: они про ЭТОТ список путей, и модель
  // читает их там же, где сам список. Фактичность карты всё равно проверяет страж
  // (`explorationPathProblem`) — блок снижает цену, а не снимает проверку.
  if (i.stage.id === 'explore' && i.exploreIndex !== undefined) {
    const flatBudget = INDEX_BLOCK_BYTES[i.flow];
    // Окно известно — считаем остаток: базовый промпт (без индекса) сам по себе может уже
    // быть близко к потолку маленькой модели, и плоская константа блока это не видит (см.
    // комментарий у `BuildPromptInput.contextWindow`). Окно не задано (sdk/облако без
    // объявленного потолка) — прежнее поведение, плоская константа.
    const usedBytes =
      systemBytes +
      Buffer.byteLength(parts.join('\n'), 'utf8') +
      (extraBlockText === null ? 0 : Buffer.byteLength(extraBlockText, 'utf8'));
    const budget =
      i.contextWindow === undefined
        ? flatBudget
        : Math.max(
            0,
            Math.min(flatBudget, i.contextWindow * BYTES_PER_TOKEN_ESTIMATE - usedBytes - EXPLORE_INDEX_RESPONSE_MARGIN_TOKENS * BYTES_PER_TOKEN_ESTIMATE),
          );
    if (budget > 0) {
      parts.push(
        '## Индекс проекта (собран рантаймом)',
        '',
        'Дерево, символы и кандидаты ниже прочитаны рантаймом из рабочего дерева при сборке ' +
          'промпта. Пути ниже существуют — карту кодовой базы составляй из них. Файл, которого ' +
          'здесь нет, в карту без `Read` не попадает; файл, который предстоит создать, называй в ' +
          'разделе о будущих правках с пометкой «новый». Список кандидатов — подсказка по ' +
          'ключевым словам задачи, не карта: что из него относится к делу, решаешь ты.',
        '',
        renderIndexBlock(i.exploreIndex, budget),
      );
    } else {
      // Окну не хватает места даже под минимальный блок — молчание было бы тише отказа:
      // модель осталась бы без предупреждения, почему подсказок по коду не пришло.
      parts.push(
        '## Индекс проекта (собран рантаймом)',
        '',
        '_Пропущен рантаймом: базовый промпт этапа уже занимает окно контекста модели ' +
          `(${i.contextWindow} токенов) без запаса под ответ. Разведку по коду веди сама ` +
          '(`Read`/`Grep`/`Glob`) — подсказок по файлам-кандидатам и переиспользованию в ' +
          'этом ходу не будет._',
      );
    }
  }

  // Prefetch файлов плана — только этап 5 и только флоу loop: сильной модели flow sdk
  // дешевле прочитать самой, чем возить это в контексте каждым ходом.
  if (i.stage.id === 'chunk' && i.flow === 'loop') {
    const fetched: string[] = [];
    let budget = PREFETCH_TOTAL_BYTES;
    // Realpath корня — инвариант цикла и считается ДО него: внутри try каждой итерации
    // ошибка КОРНЯ маскировалась бы под «файла нет» (ревью-3). Корень не резолвится —
    // prefetch честно молчит целиком.
    let realRoot: string | null;
    try {
      realRoot = realpathSync(i.ctx.paths.projectRoot);
    } catch {
      realRoot = null;
    }
    for (const rel of realRoot === null ? [] : (i.planFiles ?? [])) {
      if (budget <= 0) break;
      // Чтение строго ВНУТРИ корня проекта. Мало отсечь абсолютные пути: `../../.ssh/…`
      // из files_to_touch (текст пишет модель) выводил чтение за корень, и содержимое
      // уезжало в промпт внешнему провайдеру МИМО pathScope — политика такой Read модели
      // отклонила бы, а prefetch её не проходил (ревью, К4/B3).
      if (isAbsolute(rel)) continue;
      const abs = resolve(i.ctx.paths.projectRoot, rel);
      const back = relative(i.ctx.paths.projectRoot, abs);
      if (back.startsWith('..') || isAbsolute(back)) continue;
      // По ФАКТИЧЕСКОМУ пути, не лексическому: симлинк внутри корня, указывающий наружу,
      // проходил лексическую проверку, и содержимое внешнего файла уезжало провайдеру
      // (ревью-2, BLOCKER) — та же дисковая планка, что у гейта записи.
      let real: string;
      try {
        real = realpathSync(abs);
      } catch {
        continue; // файла нет либо цепочка ссылок битая — читать нечего
      }
      const realBack = relative(realRoot!, real);
      if (realBack.startsWith('..') || isAbsolute(realBack)) continue;
      // Чтение по ФАКТИЧЕСКОМУ пути, а не через ссылку: подмена цели симлинка между
      // проверкой и чтением (TOCTOU) иначе протаскивала бы внешний файл (ревью-3).
      const a = readArtifact(real);
      if (!a.exists) continue;
      const cap = Math.min(PREFETCH_FILE_BYTES, budget);
      fetched.push(fence(toPosix(rel), a.text, cap));
      budget -= Math.min(cap, Buffer.byteLength(a.text, 'utf8'));
    }
    if (fetched.length > 0) {
      parts.push(
        '## Файлы плана (files_to_touch) — уже прочитаны',
        '',
        'Содержимое ниже прочитано рантаймом при сборке промпта: не трать ходы на Read этих ' +
          'файлов — правь сразу. Перечитывай файл только после СВОЕЙ правки в нём.',
        '',
        fetched.join('\n\n'),
      );
    }
  }

  if (missing.length > 0) {
    // Обязательный вход отсутствует — это ловится предусловиями до сборки промпта,
    // но если сюда всё же дошло, модель должна знать, а не додумывать.
    parts.push(
      '## Отсутствующие входы',
      '',
      `Эти обязательные артефакты не найдены: ${missing.join(', ')}. Не додумывай их содержимое.`,
    );
  }

  // Карточка фактов от человека — только на этапе 5 и ПОСЛЕ входных артефактов: у слабой
  // модели решает recency, и ответ, утонувший в середине clarification-report.md, здесь
  // повторён коротко у самого конца промпта. Замер (серии r7–r8, `docs/model-runs.md`):
  // human-кейсы — единственный порог, где 8B проигрывает 14B по существу.
  if (i.stage.id === 'chunk') {
    const block = humanFactsBlock(i.ctx.paths.clarificationReport);
    if (block !== null) parts.push(block);
  }

  if (extraBlockText !== null) {
    // Бриф ретрая ограничен константами своего рендера (12 строк хвоста, 8 находок), но
    // потолка по байтам у него не было; на окне 16k локального контура он конкурирует за
    // то же место, что и план. Режется тем же потолком, что и патч прошлой попытки —
    // тело и обрезка посчитаны выше, до блока «Индекс проекта» (см. комментарий там).
    parts.push('## Что чинить в этой попытке', '', extraBlockText);
  }

  return parts.join('\n\n');
}

export function buildPrompt(i: BuildPromptInput): PreparedPrompt {
  const skillBody = readSkillBody(i.runner.skillsDir, i.stage.skill);
  const system = `${skillBody}\n\n---\n\n${adapterBlock(i)}`;

  const specs = specsFor(i.tools ?? i.stage.tools);
  const tools = [
    ...specs.map((s) => ({
      name: i.flow === 'sdk' ? s.sdkName : s.name,
      description: s.description,
      schema: s.schema,
    })),
    // Внешние MCP-инструменты показываются оператору в том же списке и под теми же
    // именами, под какими уйдут в модель: панель промпта не должна врать про набор.
    ...(i.mcpTools ?? []).map((t) => ({
      name: t.name,
      description: t.description,
      schema: t.schema,
    })),
  ];

  return {
    presetNote:
      i.flow === 'sdk'
        ? 'Флоу sdk: сверх этого текста Claude Code добавляет собственный системный пресет ' +
          '(описание встроенных инструментов и правил харнесса). Он не редактируется и здесь ' +
          'не показан — всё остальное, что уйдёт в модель, видно ниже.'
        : null,
    system,
    user: userMessage(i, Buffer.byteLength(system, 'utf8')),
    tools,
    editedByOperator: false,
  };
}
