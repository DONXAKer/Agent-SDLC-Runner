/**
 * Вердикт этапа 6.
 *
 * Эталон методологии называет исполнителем этого расчёта `tools/flow-verdict.py` скилла
 * `sdlc-verify`. В копии методологии файла физически нет — единственное место, где эталон
 * ссылается на несуществующий инструмент. Здесь он и реализован.
 *
 * Чистая функция без I/O — по той же причине, что и политика: вердикт обязан быть
 * воспроизводимым и проверяемым таблицей, а не зависеть от того, что удалось прочитать
 * с диска. Всё чтение — в `collect.ts`, здесь только правило.
 *
 * Главное свойство: **вердикт не спрашивает модель**. Слабый локальный рецензент может
 * ошибиться в статусе гейта, но не может выдать ложный зелёный — статусы считает код,
 * а снять `⏭` подписью может только человек.
 */

import type { Verdict, VerdictAction, VerdictInput } from '@sdlc-runner/shared';

import { classifyRedVerdict } from './classify.ts';

/**
 * Таблица методологии (SDLC.md → Вердикт), строка в строку:
 *
 * | гейт прошёл                     | ✅ | не роняет                                  |
 * | гейт провалился                 | ❌ | passed=false                               |
 * | гейт включён, но не запускался  | ⏭ | passed=false, если нет подписанной строки  |
 * | гейта нет в проекте             | —  | не роняет — он в долге                     |
 * | пункт приёмки подтверждён       | ✅ | не роняет                                  |
 * | пункт опровергнут               | ❌ | passed=false                               |
 * | пункт не проверяем              | ⚠ | passed=false                               |
 *
 * Приоритетов у пунктов приёмки нет — колонки приоритета нет ни в задаче, ни в отчёте,
 * поэтому «важный» и «неважный» различить нечем. Любой `❌` роняет вердикт. Это прямо
 * оговорено в методологии и здесь не смягчается.
 */
function statusReasons(i: VerdictInput): string[] {
  const out: string[] = [];

  for (const g of i.gates) {
    if (g.status === '❌') {
      out.push(`гейт «${g.name}» провалился (❌)`);
      continue;
    }
    if (g.status !== '⏭') continue;

    // «Не запустился, потому что не было окружения» — это не неприменимость, это красный
    // вердикт и повтор, состоящий в том, чтобы запустить. Снять `⏭` может только
    // подписанная человеком строка неприменимости: рецензент того же класса, что писал
    // код, и разрешать ему одному снимать гейт значит вернуть ложный зелёный.
    if (g.inapplicableSignedBy === null || g.inapplicableSignedBy.trim() === '') {
      out.push(
        `гейт «${g.name}» включён, но не запускался (⏭), и строки неприменимости с именем ` +
          `утвердившего нет`,
      );
    }
  }

  for (const c of i.claims) {
    if (c.status === '❌') out.push(`пункт приёмки ${c.id} опровергнут (❌)`);
    // ⚠ — доказательство держится на непройденной проверке. Это не «почти да».
    else if (c.status === '⚠') out.push(`пункт приёмки ${c.id} не проверяем (⚠)`);
    // `manual` вердикт не роняет по построению — причины здесь нет. Пункт не исчезает:
    // он обязан появиться в `handoff.md` как открытая ручная проверка, и это проверяет
    // этап 7, а не этот список.
  }

  return out;
}

/** Семь условий вне статусов. Каждое роняет вердикт само по себе. */
function nonStatusReasons(i: VerdictInput): string[] {
  const out: string[] = [];

  // 1. Главный выход ревью. Без этого условия прогон с зелёными гейтами уходит в коммит
  //    с известным дефектом — расхождение есть, а пункта приёмки на это поведение нет.
  if (i.confirmedReviewFindings > 0) {
    out.push(
      `подтверждённых расхождений из ревью: ${i.confirmedReviewFindings} — каждое роняет ` +
        `вердикт, даже если пункта приёмки на это поведение нет`,
    );
  }

  // 2. Гейт включён и должен отчитываться на этом этапе, а строки в отчёте нет.
  for (const name of i.enabledGatesMissingFromReport) {
    out.push(`включённый гейт «${name}» в отчёте не отчитался ни одной строкой`);
  }

  // 3. Долг, за который никто не отвечает. «Никто не делает и никто не решал» —
  //    ровно то, что методология называет роняющим вердикт.
  for (const row of i.openDebtRows) {
    out.push(
      `строка долга «${row}» в наборе не закрыта: нет ни ручной проверки с именем и датой, ` +
        `ни принятого риска с подписью`,
    );
  }

  for (const inv of i.brokenInvariants) out.push(`нарушен инвариант: ${inv}`);
  for (const r of i.regressions) out.push(`регрессия — откат ранее работавшего поведения: ${r}`);

  // 6. Путь плана, помеченный «не сделано». Второй вариант — «не потребовалось, потому
  //    что X» — это правка плана, и сюда он не попадает: сборщик отсеивает его раньше.
  for (const p of i.plannedPathsUntouched) {
    out.push(`путь плана «${p}» помечен «не сделано»`);
  }

  // 7. Артефакт этапа 5 не соответствует рабочему дереву — проверять нечего, доказательство
  //    подделано или устарело.
  if (!i.diffMatchesTree) {
    out.push('перегенерированный diff не совпал с патчем попытки — артефакт этапа 5 устарел');
  }

  return out;
}

/**
 * Действие после красного вердикта.
 *
 * Возврат на доработку — умолчание. Эскалация — не «сильно плохо», а «повторять
 * бессмысленно»: бюджет исчерпан, две попытки подряд дали один и тот же diff, либо
 * классификатор (`classify.ts`) сам сказал «чинить не в chunk'е» (`back-to-plan` —
 * вылазка за границы плана, `escalate-model` — рецензент разошёлся с прогоном).
 * Здесь не спрашивается мнение модели о том, чинимо ли: `classifyRedVerdict` — таблица
 * по уже посчитанным полям `VerdictInput`, тот же источник, что и у причин `passed`, а
 * не текст, который пишет отчёт. `fix-in-chunk` остаётся `retry` — обычный красный,
 * причину которого исполнитель может закрыть повторной попыткой в том же
 * `files_to_touch`.
 */
function decideAction(
  i: VerdictInput,
  passed: boolean,
  disagreements: readonly string[],
): { action: VerdictAction; why: string[] } {
  if (passed) return { action: 'continue', why: [] };

  // Красный из-за окружения — раньше всех прочих разборов. Условие узкое намеренно: ни один
  // гейт не провалился по существу (`❌`), а всё, что уронило вердикт, — гейты, которые не
  // смогли ЗАПУСТИТЬСЯ. Повторная попытка на этой машине даст ровно то же, поэтому и
  // «доработать» здесь нечего: чинится среда, а номер попытки остаётся за следующей
  // настоящей попыткой (`SDLC.md` → этап 6, «Красный из-за окружения»).
  const blockedGates = i.gates.filter((g) => g.envBlocked === true && g.inapplicableSignedBy === null);
  const failedGates = i.gates.filter((g) => g.status === '❌');
  const claimsBad = i.claims.some((c) => c.status === '❌' || c.status === '⚠');
  if (
    blockedGates.length > 0 &&
    failedGates.length === 0 &&
    !claimsBad &&
    i.confirmedReviewFindings === 0 &&
    i.brokenInvariants.length === 0
  ) {
    return {
      action: 'blocked_env',
      why: [
        `красный из-за окружения: не смогли запуститься гейты ${blockedGates
          .map((g) => `«${g.name}»`)
          .join(', ')}. Их код возврата свидетельствует о машине, а не о работе — ` +
          'чинится среда, номер попытки не занят',
      ],
    };
  }

  const why: string[] = [];
  if (i.noProgress) {
    why.push(
      'две попытки подряд дали один и тот же diff по существу — это остановка, а не ' +
        'следующая попытка',
    );
  }
  if (i.attempt >= i.attemptBudget) {
    why.push(`бюджет попыток исчерпан: ${i.attempt} из ${i.attemptBudget}`);
  }
  if (why.length > 0) return { action: 'escalate', why };

  const cause = classifyRedVerdict(i, disagreements);
  if (cause !== null && cause.suggest !== 'fix-in-chunk') {
    return {
      action: 'escalate',
      why: [
        `причина красного вердикта — «${cause.kind}» (${cause.suggest}): это не то, что ` +
          'чинится повторной попыткой в пределах текущего плана',
      ],
    };
  }

  return { action: 'retry', why: [] };
}

/**
 * Отчёт, из которого не удалось прочитать ни одного факта.
 *
 * `passed` считается как «нет причин упасть», и пустой вход давал зелёный вердикт: у
 * рецензента поехала форма (колонка названа `№` вместо `id`, таблица гейтов не
 * распозналась), фактов ноль, причин ноль — «принято». Отсутствие доказательства не есть
 * доказательство отсутствия, поэтому пустота ронять вердикт обязана.
 */
function evidenceProblem(i: VerdictInput): string | null {
  if (i.claims.length > 0 || i.gates.length > 0) return null;
  return (
    'в отчёте приёмки не прочитан ни один гейт и ни один пункт приёмки — ' +
    'форма отчёта не разобралась. Вердикт по пустому отчёту не считается: проверь, что ' +
    'таблица пунктов имеет колонку «id», а таблица гейтов — колонки «Гейт» и «Статус».'
  );
}

/**
 * `disagreements` — расхождения отчёта с фактическим прогоном (`collectVerdictInput`).
 * Нужны только классификатору (`escalate-model`, когда рецензент разошёлся с прогоном);
 * на `passed`/`reasons` не влияют — те решаются исключительно полями `VerdictInput`,
 * как и раньше.
 */
export function computeVerdict(i: VerdictInput, disagreements: readonly string[] = []): Verdict {
  const evidence = evidenceProblem(i);
  const reasons = [
    ...(evidence === null ? [] : [evidence]),
    ...statusReasons(i),
    ...nonStatusReasons(i),
  ];
  const passed = reasons.length === 0;
  const { action, why } = decideAction(i, passed, disagreements);
  return { passed, action, reasons: [...reasons, ...why] };
}
