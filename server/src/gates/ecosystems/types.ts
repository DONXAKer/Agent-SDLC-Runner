/**
 * Экосистема сборки: всё, что рантайм знает о языке проекта, в одном описании.
 *
 * До реестра это знание было размазано лестницей `if` в детекте сборки, полем
 * `needsNodeModules`, прибитым к npm, и четырьмя закрытыми регулярками анти-обходного
 * гейта. Добавление языка требовало правки ядра в четырёх местах, и молчаливый пропуск в
 * одном из них выглядел как «гейт зелёный», а не как «язык не поддержан».
 *
 * Здесь только данные и чистые функции: ни файловой системы, ни процессов. I/O живёт в
 * `builtin/index.ts`, как и раньше.
 */

export interface BuildSystem {
  /** Команда сборки относительно каталога модуля. */
  build: string;
  /** Команда прогона тестов. `null` — раннера у этой системы нет. */
  test: string | null;
  /**
   * Каталог установленных зависимостей относительно модуля. `null` — устанавливать нечего.
   *
   * Путём, а не булевым `needsNodeModules`: имя `node_modules` было вшито в общий код,
   * и любая другая экосистема с зависимостями (venv, vendor) пришлось бы описывать
   * вторым спецслучаем рядом.
   */
  depsDir: string | null;
}

export interface EcosystemEnv {
  /** Имена файлов в каталоге модуля — без путей. */
  files: ReadonlySet<string>;
  /** Содержимое `package.json`, если он есть. Читает вызывающий: здесь I/O нет. */
  packageJson: string | null;
}

export interface Ecosystem {
  /** Ключ для конфига и сообщений. */
  id: string;
  /** Человеческое имя — попадает в текст гейта. */
  label: string;
  /**
   * Файлы, наличие любого из которых делает каталог модулем этой экосистемы.
   *
   * Отдельно от `commands`, потому что вопрос «это вообще модуль?» задаётся при поиске
   * каталога сборки в моно-репо, когда команды ещё не нужны.
   */
  manifests: readonly string[];
  /** Команды по составу каталога. `null` — манифест есть, а собирать нечем. */
  commands(env: EcosystemEnv): BuildSystem | null;
  /**
   * Расширения исходников (со точкой, в нижнем регистре) — для гейтов, которым нужно
   * отличить код от документации.
   */
  codeExt: readonly string[];
  /**
   * Проверка синтаксиса одного файла, когда полноценно собрать нечем. `undefined` —
   * дешёвой проверки у этой экосистемы нет, и гейт честно скажет об этом.
   *
   * Возвращает команду и аргументы отдельно: путь уходит аргументом, а не вклеивается в
   * строку команды.
   */
  syntaxCheck?: (absFile: string) => { cmd: string; args: readonly string[] };
  /** Маркеры отключённого теста в добавленной строке diff. */
  disableMarkers: readonly string[];
  /** Признаки объявления теста — по ним считается, не удалили ли тесты. */
  testDecl: readonly string[];
}
