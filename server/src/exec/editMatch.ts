/**
 * Поиск фрагмента правки, когда дословный не нашёлся.
 *
 * Модель переписывает шаблонную строку, склеивая ЖЁСТКИЙ ПЕРЕНОС пробелом: в файле стоит
 * «…и обязательные\n  секции› / ⏭ — гейт в долге», а в `old_string` приходит то же самое в
 * одну строку. Дословное сравнение не совпадёт никогда, сколько бы раз модель ни повторяла
 * попытку, — и повторяет она именно эту, потому что по её представлению строка выглядит
 * так. Замер 2026-09-04 (`polza:ministral-14b`, 14 семейств фикстур): виток `explore`
 * встал на двух таких строках, промахнувшись по ним 5 и 6 раз подряд, пока анти-цикл не
 * погасил этап; тот же класс записан в `CLAUDE.md` как «44 промаха `Edit` на пять рабочих
 * копий из-за переноса строки внутри поля шаблона».
 *
 * Поэтому: пробельный промежуток в `old_string` совпадает с ЛЮБЫМ пробельным промежутком
 * файла. Границы фрагмента при этом остаются дословными — это не «похожий текст», а тот же
 * текст, иначе перенесённый.
 *
 * Мягкий поиск — ТОЛЬКО запасной путь: дословное совпадение ищется первым и выигрывает
 * всегда, а неоднозначность (два подходящих места) остаётся отказом. Направление ошибки то
 * же, что у всего инструмента: лучше отказать и назвать причину, чем записать не туда.
 */

import { escapeRe } from '../artifacts/artifact.ts';

export type LooseMatch = { start: number; end: number } | 'none' | 'ambiguous';

/**
 * Правка с переносами `\n` против файла с окончаниями `\r\n`.
 *
 * Модель пишет `old_string` через `\n` всегда, а файл на Windows бывает CRLF — и бланки витка
 * тоже: эталон методологии выписан с `core.autocrlf=true`, и рантайм раскладывает формы из
 * его рабочей копии. Мягкий поиск ниже переносы уравнивает, но только без `replace_all`;
 * с ним правка шла дословно и промахивалась по любому многострочному фрагменту. Замер
 * 2026-09-25 (`bench/traces/raw`): `gpt-oss-20b` ставит `replace_all: true` в 44 % правок,
 * 17 из 36 многострочных таких правок получили «фрагмент не найден», и на них сгорел ход
 * chunk серии s2 целиком.
 *
 * Переводится и `new_string` — файл сохраняет свои окончания, а не получает смешанные.
 * Дословное совпадение как есть по-прежнему первое: файл со смешанными окончаниями, где
 * фрагмент лежит в LF-части, не должен пострадать от перевода.
 */
export function adaptEol<E extends { oldStr: string; newStr: string }>(text: string, e: E): E {
  if (!e.oldStr.includes('\n') || e.oldStr.includes('\r') || !text.includes('\r\n')) return e;
  if (text.includes(e.oldStr)) return e;
  const crlf = (s: string): string => s.replace(/\r?\n/g, '\r\n');
  const oldStr = crlf(e.oldStr);
  return text.includes(oldStr) ? { ...e, oldStr, newStr: crlf(e.newStr) } : e;
}

export function findLooseRange(text: string, oldStr: string): LooseMatch {
  // Фрагмент без пробелов переносом сломать нельзя — мягкому поиску здесь нечего дать,
  // кроме риска: он выродился бы в дословный, уже отработавший выше.
  if (!/\s/.test(oldStr)) return 'none';

  // Экранирование ДО подмены пробелов: escapeRe пробелов не трогает, а обратный порядок
  // экранировал бы уже вставленный `\s+` и искал бы его буквально.
  const pattern = escapeRe(oldStr).replace(/\s+/g, '\\s+');
  const re = new RegExp(pattern, 'g');

  const first = re.exec(text);
  if (first === null) return 'none';
  // Второе совпадение делает выбор неопределённым — а угадывать место записи нельзя.
  if (re.exec(text) !== null) return 'ambiguous';
  return { start: first.index, end: first.index + first[0].length };
}
