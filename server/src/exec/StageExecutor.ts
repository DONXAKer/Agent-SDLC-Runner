/**
 * Интерфейс исполнителя этапа — уровень этапа, а не отдельного запроса.
 *
 * Реализаций две: `SdkExecutor` (Claude через Agent SDK, оплата по Max-подписке) и
 * `LoopExecutor` (свой цикл tool-use для локальных моделей). UI не знает, какая из них
 * работает — кроме бейджа маршрута в шапке.
 *
 * Всё, что похоже на политику, живёт не здесь: исполнитель обязан нормализовать вызов и
 * отдать его в `onToolRequest`, а решение принимают общие для обоих флоу чистые функции.
 */

import type { Decision, NormalizedCall, PreparedPrompt, ToolName, Usage } from '@sdlc-runner/shared';

export interface ExecHooks {
  /** Текст ассистента по мере поступления. */
  onText: (text: string) => void;
  onThinking: (text: string) => void;
  /**
   * Единственная точка, через которую проходит вызов инструмента. Держит промис, пока
   * политика и оператор не дадут ответ.
   */
  onToolRequest: (
    call: NormalizedCall,
    /**
     * `toolName` — как вызов назвал исполнитель: по нему гейт перепроверяет правку.
     * `rawInput` — аргументы инструмента ДО нормализации. Нужны для правки оператором:
     * интерфейс присылает только изменённые поля, и без исходных мержить их не с чем —
     * `Edit` с правленым путём приходил без `new_string`, и одобренная правка стирала
     * файл вместо замены строки.
     */
    meta: {
      requestId: string;
      toolName: string;
      rawInput: Record<string, unknown>;
      /**
       * Права ТОГО, кто сейчас вызывает: у вложенного субагента это пересечение прав
       * этапа с его объявленными правами.
       *
       * Раньше сужение прав субагента доходило только до списка инструментов, который
       * показывают модели, а политика решала по правам этапа — то есть `sdlc-locator`,
       * объявленный без права записи, получал `Write` на этапе `chunk`, стоило модели
       * назвать инструмент, которого ей не показывали. Права обязаны доезжать до
       * единственной точки решения, иначе они держатся на послушании модели.
       */
      callerTools: readonly ToolName[];
    },
  ) => Promise<Decision>;
  onToolResult: (meta: {
    requestId: string;
    ok: boolean;
    summary: string;
    durationMs: number;
    /** Текст ошибки инструмента, когда исполнитель его знает — см. `RunEvent.tool_result.detail`. */
    detail?: string;
  }) => void;
  /** Вопрос человеку из инструмента `AskHuman`. Возвращает ответы по id вопроса. */
  onAskHuman: (call: NormalizedCall) => Promise<Record<string, string[]>>;
  onUsage: (usage: Usage) => void;
  /**
   * Диагностика, которая не роняет этап, но которую нельзя проглотить. Сюда попадает,
   * например, вызов инструмента, проскочивший мимо гейта одобрений.
   */
  onWarn: (message: string) => void;
  /**
   * Трение цикла: то, на чём модель буксует, а не то, что она сделала.
   *
   * Все четыре вида цикл и так детектирует, но до этого хука они уходили только текстом
   * замечания самой модели — то есть после прогона нельзя было ответить, на чём сгорели
   * ходы: на длинных результатах, на схемах инструментов или на политике. Для локального
   * контура это главный измеряемый признак, ради него хук и заведён.
   */
  onFriction: (kind: FrictionKind) => void;
}

/** Виды трения цикла — считаются по этапам и попадают в метрики витка. */
/**
 * Виды трения цикла. `reminder` — отправленное моделью напоминание стража.
 *
 * Считать его внутри самого стража нельзя: страж — предикат, и после появления спасения
 * артефакта он зовётся дважды за ход (до и после). Счётчик мерил бы вызовы предиката, а не
 * напоминания: удачное спасение давало +1 «напоминание», которого модель не получала.
 */
export type FrictionKind = 'repeat' | 'badJson' | 'denied' | 'truncated' | 'reminder';

/** Субагент этапа: у него собственные права, и это конструкция, а не просьба. */
export interface SubagentDef {
  name: string;
  description: string;
  prompt: string;
  /** `null` — строки `tools:` в файле агента нет: наследует права вызывающего. */
  tools: string[] | null;
  model: string | null;
}

/**
 * Внешние MCP-серверы, выданные этапу.
 *
 * Набор инструментов приходит СЮДА уже отобранным, а не считается внутри исполнителя:
 * список для показа оператору (`buildPrompt`) и список, уходящий в модель, обязаны быть
 * одним и тем же, иначе панель промпта врёт.
 */
export interface McpAccess {
  /** Что показать модели: полные имена `mcp__сервер__инструмент` со схемами. */
  tools: readonly { name: string; description: string; schema: Record<string, unknown> }[];
  /**
   * Исполнение вызова во флоу `loop`. Флоу `sdk` этим не пользуется: там соединения
   * держит сам SDK, и два клиента к одному редактору спорили бы за одну PIE-сессию.
   */
  call: (
    server: string,
    tool: string,
    args: Record<string, unknown>,
    signal: AbortSignal,
  ) => Promise<{ ok: boolean; text: string }>;
  /** Конфиги серверов для `mcpServers` Agent SDK — только для флоу `sdk`. */
  sdkServers: Readonly<Record<string, unknown>>;
  /** Шаблоны опросных инструментов: их повтор не считается топтанием на месте. */
  pollingTools: readonly string[];
}

export interface ExecRequest {
  prompt: PreparedPrompt;
  /** Корень целевого проекта — рабочий каталог агента. */
  cwd: string;
  model: string;
  allowedTools: readonly ToolName[];
  /** Каталоги вне проекта, доступные агенту на чтение (формы методологии, тексты этапов). */
  readOnlyDirs: readonly string[];
  /** Субагенты, доступные на этом этапе. */
  subagents: readonly SubagentDef[];
  /** Внешние MCP-серверы. `null` — на этом этапе MCP не выдан. */
  mcp: McpAccess | null;
  /**
   * Проверка перед тем, как принять «ход завершён»: возвращает замечание или `null`.
   *
   * Заведена по наблюдению: локальная модель объявляет ход законченным, не записав ни
   * одного артефакта, и этап считается пройденным, хотя на диске пусто. Замечание даёт ей
   * доделать работу в том же этапе — тем же приёмом, каким цикл уже отвечает на повтор
   * вызова. `null` — стража нет.
   */
  finishGuard: (() => string | null) | null;
  /**
   * Попытка принять артефакт, напечатанный в ответ текстом вместо вызова инструмента.
   *
   * Возвращает строку о том, что записано, либо `null` — брать было нечего. Вызывается
   * ТОЛЬКО когда страж уже сказал, что артефакт не заполнен: это не альтернативный путь
   * записи, а спасение хода, который иначе сгорит впустую. Сама запись идёт обычным
   * путём — политика и гейт одобрения, см. `run/salvage.ts`.
   *
   * `null` — спасать нечем (флоу, где модель зовёт инструменты как положено).
   */
  salvageFromText: ((text: string) => Promise<string | null>) | null;
  maxTurns: number;
  maxBudgetUsd: number | null;
  /**
   * Сколько уже потрачено ВНЕ этого вызова `run()` — другими маршрутами ансамбля и
   * прогонами вышестоящих этапов.
   *
   * Без этого слагаемого потолок «$N на виток» переставал быть потолком: каждый маршрут
   * ансамбля и каждый вложенный субагент получали полный бюджет проекта заново и
   * сверяли его со своим локальным счётчиком, так что виток с тремя рецензентами мог
   * потратить втрое больше объявленного.
   */
  spentUsdBefore?: number;
  /**
   * Отмена прогона. Без неё «отменить» только меняло статус в UI, а исполнитель
   * продолжал крутиться, тратя бюджет и создавая новые запросы на одобрение.
   */
  signal: AbortSignal;
}

export interface StageResult {
  ok: boolean;
  /** Последний текст ассистента — то, чем этап отчитался. */
  finalText: string;
  usage: Usage;
  /** Причина завершения человеческим языком. */
  note: string;
}

export interface StageExecutor {
  readonly flow: 'sdk' | 'loop';
  run(req: ExecRequest, hooks: ExecHooks): Promise<StageResult>;
}
