/**
 * Ведущие блоки размышления (`<think>…</think>`) в тексте ответа локальных моделей.
 *
 * Root-cause (серия скрининга рецензентов 2026-09-27/28, `docs/model-runs.md`):
 * `OpenAiCompatProvider` возвращал поле `content` дословно в `ChatTurn.text` — think
 * вырезался только ВНУТРИ разбора текстовых tool-вызовов (`textToolCalls`/`toolCallStart`,
 * этого же файла), а не в самом возвращаемом тексте. `reasoning_content` (поле, куда часть
 * серверов кладёт рассуждение отдельно от `content`) не читается вовсе — читать его не
 * нужно: сервер, отделяющий рассуждение так, отдаёт в `content` уже чистый текст.
 *
 * Жертва — весь машиночитаемый канал этапа 6 и `FormFill`: `isNoAnswer`/`parseFindingAnswer`
 * (`run/reviewFill.ts`), `parseAxisAnswer`, `cleanFieldAnswer` (`exec/FormFillExecutor.ts`),
 * `extractReviewJson` (`run/stages/verify/reviewer.ts`) — первый ```json-блок ответа мог
 * оказаться черновиком ВНУТРИ think, а не итоговым ответом. Класс моделей, которые пишут
 * `<think>` в `content` без разделения (lfm2.5), проваливал разбор не из-за непонимания
 * задачи, а из-за формы ответа.
 */

/** Один ведущий ЗАКРЫТЫЙ блок думания, с ведущими пробелами ПЕРЕД тегом, БЕЗ пробелов после. */
const THINK_BLOCK_LEAD = /^\s*<think>[\s\S]*?<\/think>/;

/**
 * Позиция конца всех ведущих ЗАКРЫТЫХ блоков `<think>…</think>` подряд (0, если их нет).
 *
 * Общий примитив для `stripLeadingThink` (этот файл) и `sequenceStart`
 * (`OpenAiCompatProvider.ts` — начало последовательности вызовов инструментов текстом):
 * до вынесения сюда это был один и тот же цикл с одной и той же регуляркой, продублированный
 * в двух файлах — правка формата think в одном месте не задела бы другое (code-review-all,
 * 2026-09-28).
 */
export function leadingThinkEnd(text: string): number {
  let pos = 0;
  for (;;) {
    const m = THINK_BLOCK_LEAD.exec(text.slice(pos));
    if (m === null) break;
    pos += m[0].length;
  }
  return pos;
}

/**
 * Снимает ведущие ЗАКРЫТЫЕ блоки `<think>…</think>` (может быть несколько подряд).
 *
 * `<think>` в СЕРЕДИНЕ содержательного текста не трогается — модель вправе рассуждать
 * вслух между двумя содержательными абзацами, и вырезать это значило бы терять текст,
 * который парсеры не путают с think (они читают текст целиком, а не только начало).
 *
 * Текст, начинающийся с НЕЗАКРЫТОГО `<think>` (генерация оборвана внутри рассуждения,
 * например лимитом длины ответа), НЕ схлопывается в `''`. Первая редакция так делала —
 * «оборвано в рассуждении = ответа нет» — и этим завела РЕГРЕССИЮ (code-review-all,
 * 2026-09-28): `isNoAnswer('')` (`run/reviewFill.ts`) считает пустую строку явным «нет»,
 * то же самое поле, которым отмечен НАСТОЯЩИЙ отрицательный ответ рецензента. Оборванная
 * генерация тем самым проходила как «дефектов нет» — и в отчёт (0 находок вместо ошибки
 * разбора), и в метку корпуса (`accepted: true`, обрубленный ответ учился бы как хороший
 * пример), и в пробу `caseReviewClean` (ложный проход квалификации вместо честного
 * провала по таймауту/лимиту). Недописанная рассуждение-прosa, оставленная как есть, уже
 * достаточно ломает разбор сама по себе: `isNoAnswer` не совпадает с `нет/no/none/н/п`
 * (текст непустой и не такой), а `extractReviewJson` не найдёт валидный JSON — то есть
 * то же самое «не принято», но без нового, отдельно сочинённого пути к ложному «нет».
 */
export function stripLeadingThink(text: string): string {
  return text.slice(leadingThinkEnd(text)).replace(/^\s+/, '');
}
