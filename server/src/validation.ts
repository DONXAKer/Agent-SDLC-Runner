/**
 * Проверка того, что приходит снаружи.
 *
 * Отдельным модулем, а не внутри `index.ts`: там оно недоступно тестам, потому что
 * импорт `index.ts` поднимает сервер. Проверка входа без теста — это проверка, которая
 * однажды тихо перестанет работать.
 */

/**
 * Slug становится именем каталога артефактов, поэтому он не может содержать разделителей:
 * `../../../Users/Root/.ssh` заставлял рантайм читать файлы вне проекта и вклеивать их
 * содержимое в промпт. Политика здесь не помогает — читает сам рантайм, а не агент.
 */
const SLUG_RE = /^[a-zA-Z0-9][a-zA-Z0-9._-]{0,63}$/;

export function badSlug(slug: string): string | null {
  if (!SLUG_RE.test(slug)) {
    return 'slug может содержать только латиницу, цифры, точку, дефис и подчёркивание (до 64 символов)';
  }
  if (slug === '.' || slug === '..' || slug.includes('..')) return 'slug не может содержать «..»';
  return null;
}
