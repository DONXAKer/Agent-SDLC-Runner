/**
 * Пути перед показом человеку.
 *
 * Сервер отдаёт абсолютные нативные пути (`D:\Проекты\X\.sdlc\...`), и целиком они
 * нужны разве что в `title` по ховеру: в блокерах и артефактах читается хвост
 * относительно `projectRoot`, а дисковый префикс занимал 90% строки.
 */

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Регэксп-источник корня, где каждый разделитель сматчен обоими вариантами (`/` и `\`):
 * сервер строит пути нативными разделителями, а корень в конфиге может быть записан
 * иначе — сравнивать буквально значило бы не замечать совпадений.
 */
function rootSource(root: string): string {
  return root
    .split(/[/\\]+/)
    .filter((seg) => seg !== '')
    .map(escapeRegExp)
    .join('[/\\\\]');
}

/**
 * Заменяет вхождения абсолютного `root` в строке на относительный путь.
 *
 * Корень вырезается только когда он — ПРЕФИКС пути: после него обязан идти разделитель
 * или конец строки, иначе `D:\Проекты\Xy\…` при корне `D:\Проекты\X` превращался бы
 * в `y\…` — путь ломался молча. Остаток возвращается с разделителями `/`.
 * Строки без корня возвращаются как есть.
 */
export function relativizePaths(root: string, text: string): string {
  const norm = root.replace(/[/\\]+$/, '');
  // Корень из одного сегмента (буква диска) совпадал бы с каждым путём на этом диске.
  if (norm.split(/[/\\]+/).filter((seg) => seg !== '').length < 2) return text;
  // Lookahead после корня: разделитель, пробел или конец строки. Без него корень
  // `…\X` сматчился бы внутри `…\X-extra`, и хвост пути обрезался бы молча.
  const re = new RegExp(`(^|[^/\\\\])(${rootSource(norm)})(?:[/\\\\](\\S*))?(?=[/\\\\]|\\s|$)`, 'g');
  return text.replace(re, (_all, lead: string, _root: string, rest: string | undefined) =>
    rest === undefined ? lead : lead + rest.replace(/\\/g, '/'),
  );
}

/**
 * Хвост пути — последние `n` сегментов с многоточием. Для шапки, где сам корень
 * показывать относительно себя не из чего, а полное значение лежит в `title`.
 */
export function tailPath(path: string, n = 2): string {
  const segs = path.split(/[/\\]+/).filter((seg) => seg !== '');
  if (segs.length <= n) return path;
  return `…/${segs.slice(-n).join('/')}`;
}
