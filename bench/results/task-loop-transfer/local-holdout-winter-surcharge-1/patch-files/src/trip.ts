/**
 * Расчёт расхода топлива на поездку.
 *
 * Выдача и списание топлива идут по актам, а акт пишется кратно 100 мл: мерная ёмкость
 * на пункте выдачи имеет цену деления 100 мл, и недобор до отметки округляется в пользу
 * отчётности, а не водителя. Отсюда шаг округления и направление «вверх».
 *
 * Зимняя выдача (октябрь-апрель) идёт по зимней норме: к точному расходу добавляется
 * надбавка за холодный период. Акт на зимней норме не пишут — диспетчерская вносит
 * результат формы прямо в выдачу, отсюда точный расчёт без округления до 100 мл.
 *
 * Правило округления надбавки — общее для пакета (половина вверх), поэтому 15%
 * не придумывают собственного округления: надбавка округляется как любая другая
 * дробная сумма пакету, а итог зимнего расхода — целое число в миллилитрах.
 */

import { rateFor } from './rates.ts';

/** Шаг округления расхода: акт выдачи пишется кратно 100 мл — цена деления мерной ёмкости. */
export const FUEL_STEP_ML = 100;

/**
 * Расход топлива на поездку в миллилитрах; `null` — класс неизвестен.
 *
 * Норма хранится в дл/100 км, что численно равно мл/км (см. rates.ts), поэтому сырой
 * расход — просто произведение километров на норму, без делений и двоичных дробей.
 *
 * Округление ВВЕРХ до 100 мл: недобор до отметки акта оплачивает парк, а не водитель,
 * поэтому 1495 мл — это 1500, а не 1400.
 */
export function fuelMl(distanceKm: number, vehicleClass: string): number | null {
  const rate = rateFor(vehicleClass);
  if (rate === null) return null;
  const rawMl = distanceKm * rate;
  return Math.ceil(rawMl / FUEL_STEP_ML) * FUEL_STEP_ML;
}

/**
 * Зимняя надбавка к расходу: октябрь-апрель выдача идёт с учётом холодного периода.
 */
export const WINTER_SURCHARGE_PCT = 15;

/**
 * Расход топлива на поездку ПО ЗИМНЕЙ НОРМЕ в миллилитрах; `null` — класс неизвестен.
 *
 * Расход берётся без актовкого округления до 100 мл: зимняя норма — это плановая
 * выдача, а не запись в акт; итог получается точным, потому что сырой расход — это
 * произведение целых км на целую норму, и надбавка 15% округляется к целому мл общим
 * правилом пакета (половина вверх).
 *
 * Итог — сырой расход плюс округлённая надбавка: `7600 × 1.15 = 8740`, а не
 * «округление до 100 мл» по летнему правилу.
 */
export function winterFuelMl(distanceKm: number, vehicleClass: string): number | null {
  const rate = rateFor(vehicleClass);
  if (rate === null) return null;
  const rawMl = distanceKm * rate;
  const surchargeMl = Math.round(rawMl * WINTER_SURCHARGE_PCT / 100);
  return rawMl + surchargeMl;
}
