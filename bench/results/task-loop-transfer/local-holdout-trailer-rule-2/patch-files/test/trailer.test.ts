/**
 * Тесты расхода на поездку с прицепом: км × (норма класса + 20 мл/км), вверх до 100 мл.
 *
 * Надбавка записана у диспетчерской как 2 л/100 км = 20 мл/км — плоская прибавка к НОРМЕ
 * класса, а не множитель и не процент от расхода. Итог округляется вверх до 100 мл, как
 * обычный расход. `fuelMl` остаётся нетронутой — одиночные рейсы считаются по ней.
 */

import { strictEqual } from 'node:assert/strict';
import { describe, it } from 'node:test';

import { fuelMl, trailerFuelMl } from '../src/index.ts';

describe('расход на поездку с прицепом', () => {
  it('ровный акт: 100 км легкового с прицепом = 100 × (76 + 20) = 9600 мл', () => {
    strictEqual(trailerFuelMl(100, 'car'), 9600);
  });

  it('округление вверх до 100 мл: 13 км фургона с прицепом = 13 × (115 + 20) = 1755 мл → 1800', () => {
    strictEqual(trailerFuelMl(13, 'van'), 1800);
  });

  it('надбавка — прибавка к норме, не множитель: сырой расход по скорректированной норме', () => {
    // 20 км легкового: fuelMl сыро = 20 × 76 = 1520. С прицепом сыро = 20 × (76 + 20) = 1920 → 2000.
    // Если бы это был множитель 1.2, сыро стало бы 1520 × 1.2 = 1824 → 1900 — другое значение.
    // Различие 2000 ≠ 1900 подтверждает, что надбавка применяется к НОРМЕ, а не по проценту.
    strictEqual(trailerFuelMl(20, 'car'), 2000);
    strictEqual(fuelMl(20, 'car'), 1600); // 1520 сыро → 1600
  });

  it('неизвестный класс — null, как у rateFor', () => {
    strictEqual(trailerFuelMl(50, 'motorcycle'), null);
  });

  it('нулевой пробег — нулевой расход', () => {
    strictEqual(trailerFuelMl(0, 'car'), 0);
  });
});
