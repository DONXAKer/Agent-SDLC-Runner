/**
 * Расчёт расхода топлива на поездку.
 *
 * Выдача и списание топлива идут по актам, а акт пишется кратно 100 мл: мерная ёмкость
 * на пункте выдачи имеет цену деления 100 мл, и недобор до отметки округляется в пользу
 * отчётности, а не водителя. Отсюда шаг округления и направление «вверх».
 */

import { rateFor } from './rates.ts';

/** Шаг округления расхода: акт выдачи пишется кратно 100 мл — цена деления мерной ёмкости. */
export const FUEL_STEP_ML = 100;

/**
 * Надбавка за прицеп в мл на километр.
 *
 * Записана у диспетчерской как 2 литра на 100 км — это плоская прибавка К НОРМЕ КЛАССА,
 * а не процент или множитель от расхода: сырой расход считается по скорректированной
 * норме (норма класса + 20 мл/км), итог округляется вверх до 100 мл, как обычный расход.
 * 2 л/100 км численно = 20 мл/км — те же единицы, что и норма, без деления.
 */
export const TRAILER_SURCHARGE_ML_PER_KM = 20;

/**
 * Расход топлива на поездку в миллилитрах; `null` — класс неизвестен.
 *
 * Норма хранится в дл/100 км, что численно равно мл/км (см. rates.ts), поэтому сырой
 * расход — просто произведение километров на норму, без делений и двоичных дробей.
 *
 * Округление ВВЕРХ до 100 мл: недобор до отметки акта оплачивает парк, а не водитель,
 * поэтому 1495 мл — это 1500, а не 1400.
 */
export function fuelMl(distanceKm: number, vehicleClass: string): number | null {
  const rate = rateFor(vehicleClass);
  if (rate === null) return null;
  const rawMl = distanceKm * rate;
  return Math.ceil(rawMl / FUEL_STEP_ML) * FUEL_STEP_ML;
}

/**
 * Расход топлива на поездку С ПРИЦЕПОМ в миллилитрах; `null` — класс неизвестен.
 *
 * Прицеп — свойство поездки, а не новый класс (см. rates.ts и правила витка): таблица норм
 * не расширяется. Надбавка ПРИБАВЛЯЕТСЯ К НОРМЕ КЛАССА в величинами (20 мл/км = 2 л/100 км),
 * а не умножается по расходу: сырой расход считается по скорректированной норме
 * (норма класса + надбавка), затем итог округляется вверх до 100 мл — точно так же, как в
 * `fuelMl`. Единственное отличие — исходная величина: `rate + TRAILER_SURCHARGE_ML_PER_KM`.
 */
export function trailerFuelMl(distanceKm: number, vehicleClass: string): number | null {
  const rate = rateFor(vehicleClass);
  if (rate === null) return null;
  const rawMl = distanceKm * (rate + TRAILER_SURCHARGE_ML_PER_KM);
  return Math.ceil(rawMl / FUEL_STEP_ML) * FUEL_STEP_ML;
}
