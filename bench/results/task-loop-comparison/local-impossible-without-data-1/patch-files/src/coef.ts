/**
 * Коэффициенты пересчёта.
 *
 * Тарификация места считает не то, что товар весит, а то, сколько он занимает: лёгкая
 * объёмная коробка стоит складу столько же, сколько тяжёлая того же размера. Отсюда
 * объёмный вес и коэффициенты к нему.
 */

/** Габариты в сантиметрах: `[длина, ширина, высота]`. Порядок сторон не нормализован. */
export type DimensionsCm = readonly [number, number, number];

/**
 * Хрупкое занимает больше места, чем весит: между единицами нужны прокладки, а ряд не
 * ставится вплотную. Коэффициент к месту, не к весу — применяется при расчёте ячеек, а не
 * здесь.
 */
export const FRAGILITY_FACTOR = 1.5;

/** Шаг округления объёмного веса: место на полке занимается целыми ячейками по 100 г. */
const WEIGHT_STEP_G = 100;

/**
 * Коэффициент упаковки: товар на полку ложится не голым, а в коробе, прокладках и
 * стрейче, и тарифицировать нужно то, что реально занимает место. Значение и точка
 * применения — по регламенту приёмки: множитель к объёмному весу ПОСЛЕ формулы
 * (д×ш×в)/5, до округления.
 */
export const PACKING_FACTOR = 1.2;

/**
 * Объёмный вес в граммах.
 *
 * Отраслевая формула: (д × ш × в) в сантиметрах, делённое на 5000, даёт килограммы. Нам
 * нужны граммы, и вместо «/5000, затем ×1000» делим на 5 сразу — так в расчёте не появляется
 * дробных килограммов, которые потом пришлось бы округлять второй раз.
 *
 * Округление ВВЕРХ до 100 г: недобор до ячейки оплачивает склад, а не клиент, поэтому
 * 450 г места — это 500, а не 400.
 */
export function volumetricWeightG(dimensionsCm: DimensionsCm): number {
  const [length, width, height] = dimensionsCm;
  const rawG = (length * width * height) / 5;
  return Math.ceil(rawG / WEIGHT_STEP_G) * WEIGHT_STEP_G;
}

/**
 * Объёмный вес с учётом упаковки, в граммах.
 *
 * На полку товар ложится в упаковке — короб, прокладки, стрейч — и арендодатель
 * тарифицирует то место, что реально занято. Поэтому к объёмному весу по формуле
 * (д×ш×в)/5 применяем коэффициент упаковки, а итог округляем тем же правилом, что и
 * голый объёмный вес: вверх до 100 г, ячейка занимается целиком.
 *
 * `volumetricWeightG` остаётся без изменений: приёмке нужен голый объёмный вес для
 * сверки габаритов без упаковки.
 */
export function packedWeightG(dimensionsCm: DimensionsCm): number {
  const [length, width, height] = dimensionsCm;
  const rawG = ((length * width * height) / 5) * PACKING_FACTOR;
  return Math.ceil(rawG / WEIGHT_STEP_G) * WEIGHT_STEP_G;
}
