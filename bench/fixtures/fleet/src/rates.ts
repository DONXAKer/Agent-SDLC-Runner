/**
 * Нормы расхода топлива по классам автомобилей.
 *
 * Норма — сколько топлива автомобиль класса тратит на сто километров. Это справочные
 * значения из регламента автопарка, а не измерения конкретной машины: по ним планируют
 * выдачу и списание, факт сверяется отдельно.
 */

/**
 * Базовая норма по классам в ДЕКАЛИТРАХ на 100 км. Каждая строка имеет причину быть
 * именно такой — таблица переписана из регламента, а не подобрана.
 *
 * Единицы выбраны так, что значение численно совпадает с миллилитрами на километр
 * (1 дл = 100 мл, на 1 км — деление на 100): перевод в мл/км — это отбрасывание единиц,
 * без деления. Поэтому в таблице целые числа, и в расчётах не появляется двоичных
 * дробей вроде 24.8 × 10 = 248.00000000000003.
 */
export const FUEL_RATE_DL_PER_100KM: Readonly<Record<string, number>> = {
  // Легковой (76 дл = 7.6 л/100 км): городской цикл по бортовым журналам за год.
  car: 76,
  // Фургон (115 дл = 11.5 л/100 км): загрузка до половины, развозочный маршрут.
  van: 115,
  // Грузовой (248 дл = 24.8 л/100 км): магистраль с полной загрузкой.
  truck: 248,
};

/**
 * Норма для класса в дл/100 км; `null` — класс неизвестен.
 *
 * Молчаливого дефолта здесь нет намеренно: подставить «норму легкового» неизвестному
 * классу значило бы списать топливо грузовика по норме легкового, стоит только опечататься
 * в названии. Пусть вызывающий увидит `null` и решит сам.
 */
export function rateFor(vehicleClass: string): number | null {
  const rate = FUEL_RATE_DL_PER_100KM[vehicleClass];
  return rate === undefined ? null : rate;
}
