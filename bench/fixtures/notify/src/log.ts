/**
 * Журнал событий в памяти.
 *
 * Сюда пишут СОБЫТИЯ, а не данные. Адресат, телефон и текст уведомления — персональные
 * данные, и в журнале их нет по политике (README, «Соглашения»): журнал читают люди, у
 * которых нет права видеть, кому и что мы отправили. Отсюда и форма записи — строка без
 * структуры: положить в неё объект целиком «на всякий случай» нельзя по типу.
 *
 * В памяти, а не в файле: у стенда нет приёмника логов, а тестам нужен доступ к записям.
 */

const entries: string[] = [];

/** Записать событие. */
export function logEvent(entry: string): void {
  entries.push(entry);
}

/** Снимок журнала. Копия, а не сам массив: журнал меняется только через logEvent. */
export function events(): readonly string[] {
  return entries.slice();
}

/** Очистить журнал — для тестов, чтобы записи одного не читались в другом. */
export function resetLog(): void {
  entries.length = 0;
}
