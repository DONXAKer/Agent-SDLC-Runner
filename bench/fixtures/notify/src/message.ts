/**
 * Уведомление.
 *
 * Форма сообщения живёт отдельно от транспорта: транспорт — про доставку, а что именно мы
 * доставляем, знает отправитель и очередь. Держать тип в transport.ts значило бы править
 * границу с внешним миром всякий раз, когда у уведомления появляется новое поле.
 */

export interface OutMessage {
  /** Email адресата. Персональные данные: в журнал не пишется (см. README). */
  to: string;
  /** Текст уведомления. Тоже не для журнала: внутри бывают коды подтверждения. */
  text: string;
  /** Телефон адресата для SMS-канала, если есть. Персональные данные. */
  phone?: string;
}
