/**
 * Таблица остатков и поиск по ней.
 *
 * Таблица — источник истины инвентаризации. Она заполнена вручную по актам пересчёта, и
 * каждая строка имеет причину быть именно такой; вывести её формулой нельзя, восстановить
 * по памяти — тем более. Правки здесь делаются точечно, строка за строкой, а не
 * перегенерацией файла.
 */

/** Склады сети. Код склада — часть ключа записи (см. keys.ts), менять его нельзя. */
export type Warehouse = 'wh-msk' | 'wh-spb' | 'wh-ekb' | 'wh-vld';

/** Порядок обхода складов: так их печатает отчёт и так их суммирует stockOf. */
export const WAREHOUSES: readonly Warehouse[] = ['wh-msk', 'wh-spb', 'wh-ekb', 'wh-vld'];

/**
 * Код склада из внешнего источника (выгрузка, запрос) — наш ли это склад.
 *
 * Тип Warehouse существует только на этапе снятия типов; на границе пакета строку надо
 * проверить, иначе `STOCK_TABLE[code]` для чужого кода вернёт undefined и упадёт дальше по
 * течению с невнятным сообщением.
 */
export function isWarehouse(code: string): code is Warehouse {
  return (WAREHOUSES as readonly string[]).includes(code);
}

/** Строка инвентаризации: код позиции и количество в штуках. */
export interface StockEntry {
  /** Код позиции. В таблице заведён в верхнем регистре с дефисом — так печатает этикетку приёмка. */
  sku: string;
  /** Остаток в штуках, целое. Дробных количеств у нас нет — штучный товар. */
  qty: number;
}

