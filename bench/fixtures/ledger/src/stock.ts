/**
 * Запись по складу и коду позиции; `null`, если такой позиции на складе нет.
 *
 * Линейный проход по строкам склада. При дубликате возвращается ПЕРВАЯ запись — это
 * договорённость инвентаризации (см. STOCK_TABLE), а не случайность реализации: любая
 * замена поиска обязана её сохранить.
 */
export function findEntry(warehouse: Warehouse, sku: string): StockEntry | null {
  const rows = STOCK_TABLE[warehouse];
  for (const row of rows) {
    if (row.sku === sku) return row;
  }
  return null;
}

/**
 * Остаток позиции по каждому складу; отсутствие на складе — 0.
 *
 * Зовёт findEntry на каждый склад — то есть перебирает все строки всех складов на каждый
 * вызов. Для одной позиции это незаметно, для полного каталога — нет (см. totalQty).
 */
export function stockOf(sku: string): Record<Warehouse, number> {
  const result = {} as Record<Warehouse, number>;
  for (const wh of WAREHOUSES) {
    const entry = findEntry(wh, sku);
    result[wh] = entry === null ? 0 : entry.qty;
  }
  return result;
}

/**
 * Суммарный остаток по набору позиций на всех складах.
 *
 * Стоимость — склады × строки × позиции: stockOf на каждую позицию, findEntry на каждый
 * склад, линейный проход на каждый findEntry. На полном каталоге это тормозит, и это
 * известно; ускорять поиск можно, но семантику первой записи при дубликате — сохранить.
 */
export function totalQty(skus: readonly string[]): number {
  let sum = 0;
  for (const sku of skus) {
    const byWarehouse = stockOf(sku);
    for (const wh of WAREHOUSES) sum += byWarehouse[wh];
  }
  return sum;
}
