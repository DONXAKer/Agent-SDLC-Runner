/**
 * Ключ записи «склад + позиция».
 *
 * Резервы и журналы хранятся не по паре полей, а по одному строковому ключу: так их можно
 * класть в обычный объект и сверять с выгрузками учётной системы, где ключ печатается в
 * той же форме. Шаблон один на весь пакет — собирать ключ вручную в другом модуле нельзя,
 * иначе один и тот же резерв разойдётся на два ключа.
 */

import type { Warehouse } from './stock.ts';

/** Разделитель склада и позиции. В кодах позиций и складов не встречается. */
export const KEY_SEPARATOR = '#';

/** Ключ записи: `wh-msk#AZ-123`. */
export function keyFor(warehouse: Warehouse, sku: string): string {
  return `${warehouse}${KEY_SEPARATOR}${sku}`;
}
