/**
 * Резерв позиции под заказ.
 *
 * Резерв — обещание отгрузить: он не списывает остаток, но не даёт обещать одно и то же
 * дважды. Проверка идёт против таблицы инвентаризации (stock.ts) и против уже действующих
 * резервов (RESERVED), и порядок отказов закреплён: сначала «такого нет», потом «столько
 * не лежит», потом «уже обещано» — чтобы причина отказа называла самое раннее препятствие.
 */

import { keyFor } from './keys.ts';
import { findEntry } from './stock.ts';
import type { Warehouse } from './stock.ts';

/** Итог попытки резерва: либо поставлен, либо отказ с причиной для оператора. */
export type ReserveResult = { ok: true } | { ok: false; reason: string };

/** Опции резерва. Пока одна: комментарий в журнал, на решение не влияет. */
export interface ReserveOptions {
  /** Пометка оператора — под каким заказом резерв. В расчёт не входит. */
  note?: string;
}

/**
 * Действующие резервы: ключ записи (keys.ts) → сколько штук уже обещано.
 *
 * Таблица снята с учётной системы на дату инвентаризации и здесь не меняется: резерв
 * ставит и снимает учётная система, а этот пакет только сверяется с её выгрузкой. Ключ
 * строится ТОЛЬКО через keyFor — литерал вида `'wh-msk#EK-900'` здесь недопустим, иначе
 * при смене шаблона ключа резерв молча перестанет находиться.
 */
export const RESERVED: Readonly<Record<string, number>> = {
  [keyFor('wh-msk', 'EK-900')]: 4, // опт под сетевой контракт, отгрузка в следующем месяце
  [keyFor('wh-spb', 'BX-770')]: 7, // региональный заказ, ждёт оплаты
};

/** Сколько штук позиции уже обещано на складе; 0 — резерва нет. */
export function reservedFor(warehouse: Warehouse, sku: string): number {
  return RESERVED[keyFor(warehouse, sku)] ?? 0;
}

/**
 * Поставить резерв на `qty` штук позиции `sku` на складе `warehouse`.
 *
 * Резерв на позицию один: пока действующий не снят или не отгружен, второй не ставится —
 * так работает учётная система, и «свободный остаток» здесь либо весь остаток, либо ноль.
 * Поэтому вычитания резерва из остатка нет намеренно: оно означало бы, что резервов на
 * позицию может быть несколько.
 */
export function reserve(
  warehouse: Warehouse,
  sku: string,
  qty: number,
  opts: ReserveOptions = {},
): ReserveResult {
  void opts; // опции пока только для журнала — на решение не влияют
  if (!Number.isInteger(qty) || qty <= 0) {
    return { ok: false, reason: `количество — целое положительное число штук, получено ${qty}` };
  }
  const entry = findEntry(warehouse, sku);
  if (entry === null) {
    return { ok: false, reason: `позиции ${sku} на складе ${warehouse} нет` };
  }
  // граница включающая: остатка впритык хватает
  if (entry.qty < qty) {
    return { ok: false, reason: `на складе ${entry.qty} шт., запрошено ${qty}` };
  }
  const already = reservedFor(warehouse, sku);
  if (already > 0) {
    return { ok: false, reason: `позиция уже в резерве (${already} шт.), второй резерв не ставится` };
  }
  return { ok: true };
}
