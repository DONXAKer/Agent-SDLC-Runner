/**
 * Строки продаж — вход отчёта.
 *
 * Одна строка — один чек: кто продал и на сколько. Сумма хранится в КОПЕЙКАХ целым числом:
 * чеки складываются десятками тысяч, и рубли с плавающей точкой на такой сумме расходятся
 * с кассой на копейки — а отчёт сверяют с кассой.
 */

export interface SaleRow {
  /** Менеджер, оформивший продажу — ключ группировки в своде. */
  manager: string;
  /** Сумма чека в копейках, целое число. */
  amountK: number;
}
