/**
 * Тесты текстового отчёта.
 *
 * Здесь проверяется вёрстка — выравнивание колонок и форма пустого отчёта. Набор строк
 * один и заведомо «удобный»: суммы разные и обе много выше порога, чтобы тест говорил о
 * таблице, а не о правилах свода.
 */

import { strictEqual } from 'node:assert/strict';
import { describe, it } from 'node:test';

import { renderReport } from '../src/index.ts';

describe('текстовый отчёт', () => {
  it('таблица: заголовок, разделитель, строка на менеджера, суммы выровнены вправо', () => {
    const rows = [
      { manager: 'Иванов', amountK: 120_000 },
      { manager: 'Петрова', amountK: 250_000 },
    ];
    strictEqual(
      renderReport(rows),
      ['Менеджер       Сумма', '--------  ----------', 'Петрова   2 500,00 ₽', 'Иванов    1 200,00 ₽', ''].join('\n'),
    );
  });

  it('пустой вход — одна строка вместо таблицы', () => {
    strictEqual(renderReport([]), 'Отчёт пуст\n');
  });
});
