/**
 * Тарифная таблица и расчёт цены.
 *
 * Таблица — источник истины по цене: ставка за килограмм по зоне, заполнена вручную по
 * действующему прейскуранту. Вывести её формулой нельзя, каждая строка имеет свою причину.
 * Деньги здесь и везде в проекте — копейки целым числом: рубли с плавающей точкой в расчёте
 * не появляются.
 */

/** Целое число копеек. */
export type Kopeck = number;

/** Зоны доставки в порядке удаления от склада — в этом порядке их и печатает `list`. */
export const ZONES = ['msk', 'center', 'ural', 'far'] as const;

export type Zone = (typeof ZONES)[number];

/**
 * Ставка за килограмм в копейках.
 *
 * Все ставки — целые рубли (кратны 100): прейскурант печатается в рублях, и копейки в нём
 * не появляются. Вес приходит целыми килограммами (приёмка округляет вверх), поэтому цена
 * отправления копеек не имеет тоже — но хранится всё равно в копейках, как и всюду.
 */
export const RATE_PER_KG: Readonly<Record<Zone, Kopeck>> = {
  msk: 22_900, // своя курьерская сеть, короткое плечо
  center: 31_900, // магистраль ежедневная, плечо оплачивается перевозчику
  ural: 41_900, // один хаб на маршруте, перегруз включён в ставку
  far: 119_000, // сборный груз с авиаплечом, ставка сложилась исторически
};

/** Проверка строки из командной строки: зона ли это. */
export function isZone(value: string): value is Zone {
  return (ZONES as readonly string[]).includes(value);
}

/**
 * Цена отправления в копейках: ставка зоны × килограммы.
 *
 * Вес — целое число килограммов от одного: дробный или нулевой вес сюда не приходит,
 * приёмка округляет вверх. Молча считать по дробному значило бы выставить цену, которой
 * нет в прейскуранте.
 */
export function priceFor(zone: Zone, kg: number): Kopeck {
  if (!Number.isInteger(kg) || kg < 1) {
    throw new Error(`вес — целое число килограммов от 1, получено ${kg}`);
  }
  return RATE_PER_KG[zone] * kg;
}
