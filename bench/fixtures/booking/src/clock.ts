/**
 * Время.
 *
 * Момент «сейчас» в проект ИНЪЕЦИРУЕТСЯ: ни одна функция не зовёт `new Date()` сама, все
 * берут его параметром или через `Clock`. Иначе тест «бронь истекла» зеленел бы до полуночи
 * и краснел после неё, и первый ночной прогон списали бы на нестабильный CI, а не на код.
 *
 * Моменты в данных — строки ISO 8601 с явным смещением (обычно `Z`, как их печатает
 * `Date#toISOString()`): строка без смещения читалась бы по часам машины, и один слот на
 * двух серверах оказался бы двумя разными слотами.
 */

/** Источник текущего момента. */
export type Clock = () => Date;

/** Настоящие часы — для рантайма, не для тестов. */
export const systemClock: Clock = () => new Date();

/**
 * Строка ISO 8601 → миллисекунды эпохи.
 *
 * Нечитаемая строка — ошибка здесь, а не `NaN` в сравнении: `NaN < x` всегда ложно, и
 * бронь с битым сроком молча числилась бы истёкшей.
 */
export function instantOf(iso: string): number {
  const ms = Date.parse(iso);
  if (Number.isNaN(ms)) {
    throw new RangeError(`момент не разбирается как ISO 8601: ${JSON.stringify(iso)}`);
  }
  return ms;
}

/**
 * Часы, остановленные на заданном моменте.
 *
 * Каждый вызов отдаёт НОВЫЙ `Date`: он мутабелен, и общий экземпляр, которому кто-то сделал
 * `setHours`, сдвинул бы «остановленное» время для всех остальных читателей.
 */
export function fixedClock(iso: string): Clock {
  const ms = instantOf(iso);
  return () => new Date(ms);
}
