/**
 * Склады.
 *
 * Справочник, а не модель: код знает про склад ровно то, что нужно, чтобы отличить один от
 * другого и показать имя в расписании. Режим работы — часы, выходные, местное время — в код
 * не вносился: его ведёт диспетчерская, и оттуда его и уточняют, когда он становится нужен.
 */

export interface Warehouse {
  /** Код склада в расписании. */
  id: string;
  /** Имя, как его называют диспетчеры. */
  name: string;
}

/** Три действующих склада. Порядок — как в расписании диспетчерской: первым идёт головной. */
export const WAREHOUSES: readonly Warehouse[] = [
  { id: 'south', name: 'Южный терминал' }, // головной: сюда идёт основной поток и первым добавляется всё новое
  { id: 'north', name: 'Северные ворота' }, // перевалка сборных грузов: доков мало, слоты короткие
  { id: 'river', name: 'Речной порт' }, // сезонный: работает в навигацию, зимой в расписании пуст
];
