/**
 * Бронь дока.
 *
 * Бронь держит слот за клиентом до срока `expiresIso`. Сейчас срок — начало слота: не
 * приехал к началу — док освобождается под следующего.
 *
 * Бронь — значение, а не изменяемая сущность: `makeHold` отдаёт новый объект и хранит СВОЙ
 * снимок слота. Слот приёмки живёт дальше и может быть поправлен (сдвинули сетку), бронь от
 * этого поехать не должна; и обратно — правка брони не должна проступать в чужой слот. Этот
 * контракт закреплён тестом, а не оставлен на совесть вызывающего.
 */

import { instantOf } from './clock.ts';
import type { Slot } from './slots.ts';

export interface Hold {
  /** Идентификатор брони. Непустая строка. */
  id: string;
  /** Снимок слота на момент брони. */
  slot: Slot;
  /** Срок брони, ISO 8601 с явным смещением. */
  expiresIso: string;
}

/**
 * Забронировать слот.
 *
 * Слот, который уже начался, бронировать поздно: бронь на него истекла бы в момент
 * создания, и `isActive` сразу отвечал бы «нет» — такая бронь не ошибка данных, а ошибка
 * вызова, и она называется здесь.
 */
export function makeHold(id: string, slot: Slot, now: Date): Hold {
  if (id.trim() === '') {
    throw new RangeError('идентификатор брони пуст');
  }
  if (instantOf(slot.startIso) <= now.getTime()) {
    throw new RangeError(`слот ${slot.startIso} уже начался — бронировать его поздно`);
  }
  return {
    id,
    slot: { startIso: slot.startIso, endIso: slot.endIso },
    expiresIso: slot.startIso,
  };
}

/**
 * Действует ли бронь в момент `now`.
 *
 * Граница включающая: в сам момент `expiresIso` бронь ещё держит док. Срок совпадает с
 * началом слота, приёмка сверяет бронь ровно в начало — и «истекла секунду назад» на пороге
 * дока было бы отказом клиенту, который приехал вовремя.
 */
export function isActive(hold: Hold, now: Date): boolean {
  return now.getTime() <= instantOf(hold.expiresIso);
}
