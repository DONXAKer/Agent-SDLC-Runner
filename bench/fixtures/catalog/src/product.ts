/**
 * Товар каталога.
 *
 * Запись — три поля, и все три обязательны: без артикула запись не найти, без названия не
 * показать на витрине, без цены не продать. Конструктор проверяет то, что типом не
 * выразить — пустой артикул и дробные копейки: TypeScript снимается на лету, и в рантайме
 * сюда приходит что угодно, в том числе из формы ввода.
 */

export interface Product {
  /** Артикул — идентификатор записи в каталоге. Непустая строка. */
  code: string;
  /** Название, как оно показывается на витрине. */
  title: string;
  /** Цена в копейках, целое неотрицательное: рублей с плавающей точкой в каталоге нет. */
  priceK: number;
}

/**
 * Собрать запись товара с проверкой полей.
 *
 * Проверки здесь, а не у потребителя: цена «10.5 копейки» всплыла бы не в каталоге, а в
 * сумме заказа — там, где уже непонятно, какая запись её принесла.
 */
export function product(code: string, title: string, priceK: number): Product {
  if (code.trim() === '') {
    throw new RangeError('артикул товара пуст');
  }
  if (!Number.isInteger(priceK) || priceK < 0) {
    throw new RangeError(`цена в копейках — целое неотрицательное число, получено ${priceK}`);
  }
  return { code, title, priceK };
}
