/**
 * Накопительная скидка.
 *
 * Ставка зависит от того, сколько клиент уже потратил у нас за всё время, а не от суммы
 * текущего заказа: скидка — благодарность за прошлое, а не торг за настоящее. Поэтому
 * счётчик покупок живёт в аккаунте, а сумма заказа приходит отдельным аргументом.
 *
 * Границы ступеней ВКЛЮЧИТЕЛЬНЫ: клиент, потративший ровно 10 000 ₽, скидки ещё не
 * получает — ступень начинается со следующей копейки. Так записано в оферте, и так же
 * проверяют в поддержке, когда клиент спрашивает, почему «ровно на границе» ничего нет.
 */

import type { Kopeck } from './money.ts';
import { percent, rub } from './money.ts';

/** Аккаунт клиента: всё, что нужно расчёту скидки, — сумма его прошлых покупок. */
export interface Account {
  id: string;
  /** Сумма всех оплаченных заказов за всё время, в копейках. */
  spentTotalK: Kopeck;
}

/**
 * Ступени: порог суммы покупок (строго больше) → процент скидки. Порядок — по убыванию
 * порога, берётся первая подошедшая ступень.
 */
const TIERS: ReadonlyArray<{ aboveK: Kopeck; pct: number }> = [
  { aboveK: rub(50_000), pct: 7 }, // постоянный клиент: покупки свыше 50 000 ₽
  { aboveK: rub(10_000), pct: 3 }, // знакомый клиент: покупки свыше 10 000 ₽
];

/** Ставка накопительной скидки в процентах: 0, 3 или 7. */
export function loyaltyRate(account: Account): number {
  for (const tier of TIERS) {
    if (account.spentTotalK > tier.aboveK) return tier.pct;
  }
  return 0;
}

/** Скидка в копейках на сумму `amountK` — процент по ставке клиента, общее округление пакета. */
export function loyaltyDiscount(account: Account, amountK: Kopeck): Kopeck {
  return percent(amountK, loyaltyRate(account));
}
