/**
 * Тесты конвертера.
 *
 * Ожидания посчитаны вручную от коэффициентов модуля и округлены по его правилу — три знака,
 * половина вверх. Температура сверяется без округления: у неё точный множитель.
 */

import { strictEqual } from 'node:assert/strict';
import { describe, it } from 'node:test';

import { cToF, kgToLb, kmToMiles, round3 } from '../src/index.ts';

describe('округление', () => {
  it('три знака, половина вверх', () => {
    // 1/16 — точная двоичная дробь: 62.5 тысячных без хвоста, ровно половина → вверх
    strictEqual(round3(0.0625), 0.063);
    strictEqual(round3(1.2344), 1.234);
  });

  it('целое не меняется', () => {
    strictEqual(round3(2), 2);
  });
});

describe('километры в мили', () => {
  it('один километр', () => {
    strictEqual(kmToMiles(1), 0.621);
  });

  it('половина километра', () => {
    strictEqual(kmToMiles(0.5), 0.311);
  });

  it('граничный кейс сотни', () => {
    strictEqual(kmToMiles(100), 62.14);
  });

  it('марафон', () => {
    strictEqual(kmToMiles(42.195), 26.219);
  });
});

describe('килограммы в фунты', () => {
  it('один килограмм', () => {
    strictEqual(kgToLb(1), 2.205);
  });

  it('десять килограммов', () => {
    strictEqual(kgToLb(10), 22.046);
  });
});

describe('градусы Цельсия в Фаренгейта', () => {
  it('точка кипения воды', () => {
    strictEqual(cToF(100), 212);
  });

  it('точка замерзания воды', () => {
    strictEqual(cToF(0), 32);
  });

  it('шкалы пересекаются на −40', () => {
    strictEqual(cToF(-40), -40);
  });

  it('десятые градуса без округления', () => {
    strictEqual(cToF(37), 98.6);
  });
});
