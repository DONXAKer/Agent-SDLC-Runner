/**
 * Конвертация единиц для отчётов.
 *
 * Величины здесь дробные: в отчёт идут километры и килограммы с десятичными долями, и
 * целочисленной модели, как у денег в копейках, у них нет. Поэтому округление фиксированное и
 * одно на модуль — три знака после запятой, половина вверх. Своя функция, а не `toFixed`:
 * тот возвращает строку, а отчёт складывает числа дальше; и правило округления должно быть
 * названо одним словом в одном месте — в конверторах его не переписывают.
 *
 * Округляется только то, что умножается на УСЕЧЁННЫЙ коэффициент: у мили и фунта в
 * десятичной записи хвост бесконечный, и без округления два отчёта по одному расстоянию
 * расходились бы в пятнадцатом знаке. Температура — см. `cToF` — под это правило не подпадает.
 */

/** Миль в километре: международная миля — 1609.344 м, 1/1.609344 с точностью до шести знаков. */
export const MILES_PER_KM = 0.621371;

/** Фунтов в килограмме: фунт — 0.45359237 кг, 1/0.45359237 с точностью до пяти знаков. */
export const LB_PER_KG = 2.20462;

/**
 * Округление до трёх знаков, половина вверх.
 *
 * Записано буквально — `floor(x·1000 + 0.5)`, — чтобы правило читалось из кода, а не из
 * документации `Math.round` (та в минус тоже округляет вверх, к +∞, но об этом надо помнить).
 */
export function round3(x: number): number {
  return Math.floor(x * 1000 + 0.5) / 1000;
}

/** Километры → мили, округлено по правилу модуля. */
export function kmToMiles(km: number): number {
  return round3(km * MILES_PER_KM);
}

/** Килограммы → фунты, округлено по правилу модуля. */
export function kgToLb(kg: number): number {
  return round3(kg * LB_PER_KG);
}

/**
 * Градусы Цельсия → Фаренгейта. БЕЗ округления — так надо.
 *
 * Шкала аффинная с точным множителем 9/5: целые и десятые градусов, какими их даёт
 * приёмка, переходят без хвоста, и `round3` здесь либо ничего не делал бы, либо — на входе с
 * бо́льшей точностью — молча её скрывал. Усечённого коэффициента, ради которого заведено
 * округление, у температуры нет.
 */
export function cToF(c: number): number {
  return (c * 9) / 5 + 32;
}
