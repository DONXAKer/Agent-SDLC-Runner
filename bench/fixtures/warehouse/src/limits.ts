/**
 * Лимиты хранения по категориям.
 *
 * Лимит — сколько единиц товара одной категории можно положить в одну ячейку. Ступень у
 * лимита ОДНА: для категории есть ровно одно число, и никакого «второго порога» или
 * «повышенного лимита сверх базового» в модели нет. Когда единиц больше лимита, приёмка
 * заводит вторую ячейку — это решает она, а не этот модуль.
 */

/**
 * Базовый лимит по категориям. Каждая строка имеет причину быть именно такой — таблица
 * заполнена по регламенту склада, а не подобрана.
 */
export const CATEGORY_LIMIT: Readonly<Record<string, number>> = {
  // Обычный товар: ограничение — грузоподъёмность полки стандартной ячейки.
  standard: 200,
  // Хрупкое: укладка не выше двух рядов, иначе нижний ряд бьётся под весом верхнего.
  fragile: 80,
  // Жидкости: ячейка с поддоном, объём поддона рассчитан на разлив шестидесяти тар.
  liquid: 60,
};

/**
 * Лимит для категории; `null` — категория неизвестна.
 *
 * Молчаливого дефолта здесь нет намеренно: подставить «200 как для standard» значило бы
 * разрешить укладку хрупкого или жидкости по нормам обычного товара, стоит только опечататься
 * в названии категории. Пусть вызывающий увидит `null` и решит сам.
 */
export function limitFor(category: string): number | null {
  const limit = CATEGORY_LIMIT[category];
  return limit === undefined ? null : limit;
}
