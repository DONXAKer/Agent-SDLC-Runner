/**
 * Выборка партии на контроль.
 *
 * Выборка случайная, чтобы контроль не подгоняли под известные позиции: если бы проверяющие
 * знали заранее, какие sku попадут на стол, к этим sku и готовились бы, а брак ехал бы в
 * остальных. Случайность здесь — свойство контроля, а не удобство реализации.
 */

/**
 * `n` случайных позиций из `items` без повторов, в порядке вытягивания.
 *
 * Вытягивание без возврата — частичное перемешивание Фишера–Йетса по копии списка: на
 * каждом шаге из оставшегося хвоста берётся один элемент и убирается из хвоста, так что
 * повтор невозможен по построению, а не по фильтрации задним числом.
 */
export function pickBatch(items: readonly string[], n: number): string[] {
  if (!Number.isInteger(n) || n < 0) {
    throw new RangeError(`размер партии должен быть целым неотрицательным числом, получено ${n}`);
  }
  if (n > items.length) {
    throw new RangeError(`партия из ${n} позиций не набирается из каталога в ${items.length}`);
  }
  const pool = [...items];
  const picked: string[] = [];
  for (let i = 0; i < n; i += 1) {
    const j = Math.floor(Math.random() * pool.length);
    picked.push(pool[j]!);
    pool.splice(j, 1);
  }
  return picked;
}
