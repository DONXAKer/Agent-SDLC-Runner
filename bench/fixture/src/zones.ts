/**
 * Тарифные зоны.
 *
 * Зона выводится из кода региона получателя и больше ни из чего: город, индекс и
 * расстояние в расчёт не входят. Это упрощение принято сознательно — тариф у нас
 * зональный, а не километражный.
 */

export type Zone = 'msk' | 'center' | 'ural' | 'far';

/** Москва и область. */
const MSK = new Set([50, 77, 90, 97, 99]);

/** Центральная Россия и Северо-Запад. */
const CENTER = new Set([31, 32, 33, 36, 37, 40, 44, 46, 47, 48, 57, 62, 67, 68, 69, 71, 76, 78]);

/** Урал и ближняя Сибирь. */
const URAL = new Set([45, 55, 56, 59, 66, 72, 74, 86, 89]);

/**
 * Зона по коду региона.
 *
 * Неизвестный код относится к дальней зоне, а не роняет расчёт: справочник регионов
 * пополняется чаще, чем выкладывается сервис, и отказ считать цену хуже, чем цена по
 * верхнему тарифу.
 */
export function zoneOf(regionCode: number): Zone {
  if (MSK.has(regionCode)) return 'msk';
  if (CENTER.has(regionCode)) return 'center';
  if (URAL.has(regionCode)) return 'ural';
  return 'far';
}

/** Все зоны в порядке удалённости — для обхода таблиц и тестов. */
export const ZONES: readonly Zone[] = ['msk', 'center', 'ural', 'far'];
