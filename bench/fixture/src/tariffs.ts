    34_900, // до 1 кг — вес ниже порога перевозчика, цена за место
    45_900, // до 2 кг — начинается повесовая тарификация магистрали
    63_900, // до 5 кг — повесовая тарификация в полный рост
    89_900, // свыше 5 кг — плюс сбор за негабаритное место у перевозчика
