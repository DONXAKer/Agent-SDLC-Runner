/**
 * Габариты отправления в сантиметрах: длина, ширина, высота.
 *
 * Порядок сторон не нормализован — приёмка вводит их так, как удобно мерить. Никакой
 * код не вправе считать первую сторону наибольшей.
 */
export type Dimensions = readonly [number, number, number];

/** Отправление, как оно приходит с приёмки. */
export interface Order {
  /** Код региона получателя. */
  regionCode: number;
  /** Вес в граммах, уже округлённый приёмкой до границы ступени. */
  weightG: number;
  /**
   * Габариты, снятые на приёмке.
   *
   * В цену они пока не входят: их фиксируют ради претензионной работы и загрузки машин.
   */
  dimensionsCm: Dimensions;
  /** Клиент. Разовое отправление приходит с уровнем `none`. */
  customer: Customer;
}

/** Разложенный расчёт — так его показывают клиенту и так же проверяют в поддержке. */
export interface Quote {
  /** Зона, в которую посчитана цена. */
  zone: Zone;
  /** Базовая цена зоны и веса, до скидки. */
  base: Kopeck;
  /** Скидка лояльности в копейках. */
  discount: Kopeck;
  /** Сумма к оплате. */
  total: Kopeck;
}

/** Базовая цена зоны и веса. */
export function basePrice(zone: Zone, weightG: number): Kopeck {
  const row = TARIFF_TABLE[zone];
  const price = row[weightStep(weightG)];
  // Строка таблицы короче числа ступеней — это дефект заполнения, а не входных данных,
  // и молча брать соседнюю ступень значит выставить клиенту чужую цену.
  if (price === undefined) {
    throw new Error(`тариф не заполнен: зона ${zone}, вес ${weightG} г`);
  }
  return price;
}

/** Наибольшая сторона отправления. */
export function longestSide(dimensions: Dimensions): number {
  return Math.max(dimensions[0], dimensions[1], dimensions[2]);
}

/** Сумма трёх измерений — обхват, которым оперируют перевозчики. */
export function dimensionSum(dimensions: Dimensions): number {
  return dimensions[0] + dimensions[1] + dimensions[2];
}

/**
 * Цена отправления.
 *
 * Порядок слагаемых значим и закреплён: сначала база по зоне и весу, затем скидка от
 * базы, и только потом вычитание. Любое новое слагаемое обязано встать в этот порядок
 * явно, а не «где получилось».
 */
export function priceFor(order: Order): Quote {
  const zone = zoneOf(order.regionCode);
  const base = basePrice(zone, order.weightG);
  const discount = discountFor(order.customer, base);
  const total = subtract(base, discount);
  return { zone, base, discount, total };
}
